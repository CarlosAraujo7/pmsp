"""Gera as tabelas do Ciclo 18-19 do artigo do CEC (cec/tab_selector.tex, cec/tab_pretest.tex, cec/tab_hosts.tex) a partir dos resultados das Entradas 197-221. Uso: python -m analysis.make_table_cec2"""
from __future__ import annotations

import glob
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
R = ROOT / "results"
OUT = ROOT / "cec"
ORDER = ["S5-discovery", "S5-heldout", "S15-discovery", "S15-heldout"]


def row(df, label):
    d = df.set_index("id")
    cells = []
    for o in ORDER:
        r = d.loc[[i for i in d.index if i.endswith(o)][0]]
        mark = "" if r.confirmada else "$^\\dagger$"
        cells.append(f"{-r.mean_d_pct:+.3f}{mark}")
    return f"{label} & " + " & ".join(cells) + " \\\\"


def selector_table():
    S = lambda k: pd.read_csv(R / f"entrada200_selector_{k}.csv")
    C = lambda k: pd.read_csv(R / f"entrada200_controls_{k}.csv")
    E = lambda k: pd.read_csv(R / f"entrada213_equalcpu_{k}.csv")
    cap = pd.read_csv(R / "entrada200_controls_by_family.csv")
    cap = cap[cap.fam == "all"].set_index(["space", "set"])
    cap2 = pd.read_csv(R / "entrada200_selector_by_family.csv")
    cap2 = cap2[cap2.fam == "all"].set_index(["space", "set"])
    caps = lambda col, t=cap: " & ".join(f"{t.loc[(o.split('-')[0], o.split('-')[1]), col]:.2f}" for o in ORDER)
    L = ["% Auto-generated by analysis/make_table_cec2.py", "\\begin{table}[t]",
         "\\caption{Offline instance-conditioned selector (trained on $5{,}720$ disjoint instances, no family information) on the published instances ($2{,}550$ discovery, $3{,}950$ held-out; $T=1000$, five seeds): gain of the selector over each reference, in percentage points of the makespan (positive: the selector is better); at equal CPU time each arm has its own cost ratio $K$; $^\\dagger$ not significant after Holm correction. Bottom: share of the oracle headroom captured (oracle of one seed per action, an upper bound; the cross-fitted oracle is a lower bound).}",
         "\\label{tab:selector}", "\\centering", "{\\scriptsize\\setlength{\\tabcolsep}{3pt}", "\\begin{tabular}{@{}lrrrr@{}}", "\\toprule",
         " & \\multicolumn{2}{c}{S5} & \\multicolumn{2}{c}{S15} \\\\ \\cmidrule(lr){2-3}\\cmidrule(l){4-5}", " & disc. & held & disc. & held \\\\", "\\midrule",
         row(S("Cval"), "vs.\\ validated action ($525$ tuning inst.)"), row(E("Cvl"), "vs.\\ validated action, equal CPU"), row(C("Cvb"), "vs.\\ static action learned on the same $5{,}720$"),
         row(C("Ccl"), "vs.\\ per-class lookup table, same $5{,}720$"), row(S("Cql"), "vs.\\ Q-Learning, equal iterations"), row(E("Cql"), "vs.\\ Q-Learning, equal CPU"), row(S("Calns"), "vs.\\ ALNS roulette, equal iterations"), row(E("Cal"), "vs.\\ ALNS roulette, equal CPU"),
         row(S("Crand"), "vs.\\ random choice"), "\\midrule",
         "Headroom captured: validated action & " + caps("cap_val", cap2) + " \\\\", "Headroom captured: lookup table & " + caps("cap_valclass") + " \\\\", "Headroom captured: selector & " + caps("cap_sel") + " \\\\", "\\bottomrule", "\\end{tabular}}", "\\end{table}"]
    (OUT / "tab_selector.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(l for l in L if "&" in l))


def pretest_table():
    """Pre-teste VNR: calibracao (42 celulas), held-out do P||Cmax (descritivo), familia F (fora da amostra) e flowshop (fora da amostra), com o tau congelado."""
    from analysis.pretest_vnr_entrada198 import evaluate
    tau = json.loads((R / "pretest_tau_entrada198.json").read_text())["tau"]
    C = pd.read_csv(R / "pretest_vnr_cells_entrada198.csv")
    rows = []

    def add(label, vnr, gq):
        x = pd.DataFrame(dict(v=vnr, g=gq)).dropna()
        e = evaluate(x.v, x.g, tau)
        rows.append((label, e["n"], e["frac_pays"], e["auc"], e["acc"], e["spearman"]))
    cal = C[C.set.isin(["synthetic", "discovery"])]
    add("P$||C_{\\max}$ calibration cells (fixes $\\tau$)", cal.vnr, cal.gq)
    add("P$||C_{\\max}$ held-out cells (explored earlier)", C[C.set == "heldout"].vnr, C[C.set == "heldout"].gq)
    F = pd.read_csv(R / "entrada199_pretest_cells.csv")
    for sp in ("S5", "S15"):
        f = F[F.space == sp]
        add(f"Family F, {sp} (out of sample)", f.vnr, f.gq)
    pf = R / "entrada197_pfsp_cells.csv"
    if pf.exists():
        P = pd.read_csv(pf)
        for sname, nm in (("syn", "synthetic"), ("ta", "Taillard")):
            p = P[P.set == sname]
            add(f"Flowshop, {nm} (out of sample)", p.vnr, p.gq)
    L = ["% Auto-generated by analysis/make_table_cec2.py", "\\begin{table}[t]",
         f"\\caption{{Pre-test of the headroom rule: the validated-gain-to-noise ratio (VNR, estimated on tuning instances only) against whether Q-Learning beats random choice in a cell, with the threshold $\\tau={tau:.3f}$ fixed on the first row. Cells with zero noise (every run at the lower bound) are excluded. Accuracy: the rule `VNR $\\geq\\tau$' predicts `Q-Learning gains'; AUC is undefined (n/a) when no evaluable cell has a gain.}}",
         "\\label{tab:pretest}", "\\centering", "{\\scriptsize\\setlength{\\tabcolsep}{3pt}", "\\begin{tabular}{@{}lrrrrr@{}}", "\\toprule", "Cells & $n$ & Q gains & AUC & Acc. & Spearman \\\\", "\\midrule"]
    fmt = lambda v: "n/a" if v != v else f"{v:.2f}"
    L += [f"{l} & {n} & {fp:.2f} & {fmt(a)} & {ac:.2f} & {sp_:+.3f} \\\\" for l, n, fp, a, ac, sp_ in rows] + ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
    (OUT / "tab_pretest.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(l for l in L if "&" in l))


def hosts_table():
    """Flowshop de permutacao (sinteticas e Taillard; F5, F15) e algoritmo genetico (G9, G18): ganhos (pontos percentuais; positivo: melhor) sobre o aleatorio."""
    from analysis.report_entrada180_agents import rel
    from analysis.report_entrada197_pfsp import load_test
    from analysis.report_entrada209_cforacle import load_pfsp
    from analysis.report_entrada219_ga import load_test as load_ga
    from analysis.report_entrada220_ga_mix import load_m
    g = lambda x, a, b: float(-rel(x[a], x[b]).mean())
    fl = {sp: load_test(sp) for sp in ("F5", "F15")}
    cf = {sp: load_pfsp(sp) for sp in ("F5", "F15")}
    sel = {}
    for sp in ("F5", "F15"):
        fs = sorted(glob.glob(str(R / f"pfspsel_test_{sp}_s*of*_entrada205.csv")))
        d = pd.concat([pd.read_csv(f) for f in fs], ignore_index=True)
        sel[sp] = d.groupby(["cls", "method"]).makespan.mean().unstack("method").reset_index()
    ga = {sp: load_m(sp) for sp in ("G9", "G18")}
    cols = [("fl", "syn", "F5"), ("fl", "syn", "F15"), ("fl", "ta", "F5"), ("fl", "ta", "F15"), ("ga", None, "G9"), ("ga", None, "G18")]
    spl = {"G9": 0, "G18": 0}

    def cell(host, setn, sp, what):
        if host == "fl":
            w = fl[sp][fl[sp].set == setn].merge(sel[sp], on="cls", how="left")
            c = cf[sp][cf[sp].set == setn]
            if what == "hb":
                return g(c, "biased", "rand")
            if what == "hc":
                return g(c, "cf", "rand")
            if what == "val":
                return g(w, "val", "rand")
            if what == "vmix":
                return None
            if what == "ql":
                return g(w, "ql", "rand")
            if what == "best":
                return max(g(w, k, "rand") for k in ("ucb", "pg", "alns", "ts"))
            if what == "qlcpu":
                return g(w, "ql", "rand_eq_ql")
            if what == "sel":
                return g(w, "sel", "rand")
        else:
            w = ga[sp]
            if what == "hb":
                return g(w, "biased", "rand")
            if what == "hc":
                return g(w, "cf", "rand")
            if what == "val":
                return g(w, "val", "rand")
            if what == "vmix":
                return g(w, "vmix", "rand")
            if what == "ql":
                return g(w, "ql", "rand")
            if what == "best":
                return max(g(w, k, "rand") for k in ("ucb", "pg", "alns", "ts"))
            if what == "qlcpu":
                return g(w, "ql", "rand_eq_ql")
            if what == "sel":
                return None
    rows = [("Oracle headroom, one seed", "hb"), ("Oracle headroom, cross-fitted", "hc"), ("Validated single action", "val"), ("Validated mixture (top 3)", "vmix"), ("Q-Learning, equal iterations", "ql"), ("Best other learner, equal iter.", "best"),
            ("Q-Learning, equal CPU", "qlcpu"), ("Offline selector", "sel")]
    L = ["% Auto-generated by analysis/make_table_cec2.py", "\\begin{table}[t]",
         "\\caption{Two further hosts: gain over random choice in percentage points of the makespan (positive: better). Left: permutation flowshop (IG of Ruiz and St\\\"utzle; $T=1000$; $360$ synthetic and $90$ Taillard instances; five (F5) and fifteen (F15) actions). Right: steady-state genetic algorithm for P$||C_{\\max}$ ($T=10{,}000$ offspring; $1{,}200$ instances; nine (G9) and eighteen (G18) crossover--mutation actions). The cross-fitted oracle chooses the action on two seeds and evaluates it on two others (four seeds per fixed action); `--' where not run. Differences between rounded rows can differ in the third decimal from the paired differences in the text, because each paired difference is taken relative to its own reference arm.}",
         "\\label{tab:hosts}", "\\centering", "{\\scriptsize\\setlength{\\tabcolsep}{1.8pt}", "\\begin{tabular}{@{}lrrrrrr@{}}", "\\toprule",
         " & \\multicolumn{2}{c}{Flowshop, synth.} & \\multicolumn{2}{c}{Flowshop, Taillard} & \\multicolumn{2}{c}{Genetic alg.} \\\\ \\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(l){6-7}", " & F5 & F15 & F5 & F15 & G9 & G18 \\\\", "\\midrule"]
    for lab, key in rows:
        vals = []
        for host, setn, sp in cols:
            v = cell(host, setn, sp, key)
            vals.append("--" if v is None else f"{v:+.3f}")
        L.append(f"{lab} & " + " & ".join(vals) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
    (OUT / "tab_hosts.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(l for l in L if "&" in l))


if __name__ == "__main__":
    selector_table()
    pretest_table()
    hosts_table()
