"""Gera cec/tab_further.tex: os concorrentes alem da bateria principal (irace, desenhos publicados de AOS, seletor offline, oraculos de malha fechada), como ganho sobre o aleatorio a iteracoes iguais, no P||Cmax sintetico e no R||Cmax. Todos os valores vem dos arquivos de resultados (Entradas 234, 240, 242, 244, 249). Uso: python analysis/make_table_cec5.py"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
P242 = pd.read_csv(R / "entrada242_pubaos_pooled.csv").set_index(["host", "space"])
I244 = pd.read_csv(R / "entrada244_irace_pooled.csv")
I244 = I244[I244.bm == 1].set_index(["host", "space"])
SEL = pd.read_csv(R / "entrada240_urselector_pooled.csv").set_index("space")
CL = pd.read_csv(R / "entrada249_closedloop_split.csv").set_index(["host", "space"])
CELLS = [("pc", "S5"), ("pc", "S15"), ("ur", "S5"), ("ur", "S15")]


def fmt(v):
    return "--" if v is None or pd.isna(v) else f"{v:+.3f}"


ROWS = [
    ("Validated single action", [P242.loc[c, "g_val"] for c in CELLS]),
    ("irace, static configuration", [I244.loc[c, "g_cfg"] for c in CELLS]),
    ("irace, tuned Q-Learning", [I244.loc[c, "g_q"] for c in CELLS]),
    ("Episodic Q-Learning~\\cite{KarimiMamaghanEtal2023}", [P242.loc[c, "g_iq"] for c in CELLS]),
    ("FRRMAB-style bandit~\\cite{LiFialhoEtal2014}", [P242.loc[c, "g_fr"] for c in CELLS]),
    ("Myopic lookahead (not budget-fair)", [CL.loc[c, "g_la8"] for c in CELLS]),
    ("Rollout lookahead (not budget-fair)", [CL.loc[c, "g_ro"] for c in CELLS]),
]

cap = ("\\caption{Competitors beyond the main battery: gain over random choice at equal iterations, in percentage points of the makespan (positive: better); $1{,}200$ instances per cell ($240$ for the rollout lookahead). "
       "The published designs are re-implemented and tuned by us; the lookahead policies are references, not upper bounds. S5, S15: five and fifteen actions. Rows can differ from the paired differences in the text (each is relative to its own reference arm).}")
L = ["% Auto-generated by analysis/make_table_cec5.py", "\\begin{table}[t]", cap, "\\label{tab:further}", "\\centering",
     "{\\scriptsize\\setlength{\\tabcolsep}{3pt}", "\\begin{tabular}{@{}lrrrr@{}}", "\\toprule",
     " & \\multicolumn{2}{c}{P$||C_{\\max}$} & \\multicolumn{2}{c}{R$||C_{\\max}$} \\\\ \\cmidrule(lr){2-3}\\cmidrule(l){4-5}",
     " & S5 & S15 & S5 & S15 \\\\", "\\midrule"]
for name, vals in ROWS:
    L.append(name + " & " + " & ".join(fmt(v) for v in vals) + " \\\\")
L += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
(ROOT / "cec" / "tab_further.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
print("\n".join(L[10:]))
