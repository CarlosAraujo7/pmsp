"""
analysis/make_table_exact_reference.py (Entrada 101)
Gera paper/f11_exact_reference.tex: por classe sintetica, GAP medio contra o LB classico e contra o LB
CERTIFICADO do arc-flow (pmsp.exact; igual ao otimo em 98,7% das instancias validadas contra o iAF) e a %
de instancias em que cada metodo devolve uma solucao PROVADAMENTE otima (makespan == LB certificado).
Fonte: results/results.csv + results/exact_reference_synthetic_entrada101.csv.
Uso: python -m analysis.make_table_exact_reference
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
res = pd.read_csv(ROOT / "results" / "results.csv")
ref = pd.read_csv(ROOT / "results" / "exact_reference_synthetic_entrada101.csv")
d = res.merge(ref[["instance", "rep", "lb_lp", "lb3"]], on=["instance", "rep"])
d["gap_lp"] = 100 * (d.makespan - d.lb_lp) / d.lb_lp
d["opt"] = d.makespan == d.lb_lp
order = res.groupby("instance").n.first().sort_values().index
meth = [("ig_ql", r"\textsc{IG-QL}"), ("ils_ql", r"\textsc{ILS-QL}"), ("multifit", r"\textsc{MultiFit}")]
rows = []
for inst in order:
    g = d[d.instance == inst]
    n, m = int(g.n.iloc[0]), int(g.m.iloc[0])
    vbs = ref[ref.instance == inst]
    cells = []
    for k, _ in meth:
        s = g[g.method == k]
        cells.append((s.gap_pct.mean(), s.gap_lp.mean(), 100 * s.opt.mean()))
    rows.append((n, m, 100 * vbs.proven.mean(), cells, 100 * ((g.groupby("rep").lb_lp.first() - g.groupby("rep").lb3.first()) / g.groupby("rep").lb3.first()).mean()))
tot = {k: 100 * d[d.method == k].opt.mean() for k, _ in meth}

lines = [
    "% Auto-generated by analysis/make_table_exact_reference.py (Entrada 101)",
    r"\begin{table}[t]",
    r"\centering",
    (r"\caption{GAP (\%) with respect to the classical lower bound (LB) and to the certified arc-flow lower bound "
     r"(LB$^{\mathrm{AF}}$), and share of instances for which a method returns a \emph{provably optimal} solution "
     r"(makespan equal to LB$^{\mathrm{AF}}$). LB$^{\mathrm{AF}}$ is the linear relaxation of the arc-flow model; it never exceeded the "
     r"optimum of the iAF reference on 150 real instances and equalled it on $98.7\%$ of them. ``Best'' is the share of instances whose "
     r"best makespan over all 23 methods is provably optimal.}"),
    r"\label{tab:f11_exact}",
    r"{\scriptsize\setlength{\tabcolsep}{3pt}",
    r"\begin{tabular}{@{}rrrrrrrrrrrr@{}}",
    r"\toprule",
    r" & & & \multicolumn{3}{c}{\textsc{IG-QL}} & \multicolumn{2}{c}{\textsc{ILS-QL}} & \multicolumn{2}{c}{\textsc{MultiFit}} & \\",
    r"\cmidrule(lr){4-6}\cmidrule(lr){7-8}\cmidrule(lr){9-10}",
    r"$n$ & $m$ & Best (\%) & GAP$_{\mathrm{LB}}$ & GAP$_{\mathrm{AF}}$ & Opt.\ (\%) & GAP$_{\mathrm{AF}}$ & Opt.\ (\%) & GAP$_{\mathrm{AF}}$ & Opt.\ (\%) \\",
    r"\midrule",
]
for n, m, best, c, _ in rows:
    (a, b, c1), (d1, d2), (e1, e2) = (c[0][0], c[0][1], c[0][2]), (c[1][1], c[1][2]), (c[2][1], c[2][2])
    lines.append(f"{n} & {m} & {best:.0f} & {a:.2f} & {b:.2f} & {c1:.0f} & {d1:.2f} & {d2:.0f} & {e1:.2f} & {e2:.0f} \\\\")
lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
out = ROOT / "paper" / "f11_exact_reference.tex"
out.write_text("\n".join(lines).replace("& & \\\\", "\\\\"), encoding="utf-8")
print("\n".join(lines[9:]))
print("proportion provably optimal over all instance-runs:", {k: round(v, 1) for k, v in tot.items()})
