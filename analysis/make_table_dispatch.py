"""
analysis/make_table_dispatch.py
=================================
Gera paper/f8_dispatch.tex: resultado do teste confirmatorio pre-registrado do
despacho a priori (Entradas 94/96), por familia e pooled. Mesmos dados e regra
de analysis/report_entrada94_dispatch_confirmatory.py (limiar 0,1 fixo).

Uso: python -m analysis.make_table_dispatch
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from analysis.report_entrada94_dispatch_confirmatory import (  # noqa: E402
    holdout_dup_ratios, IG_RES, ILS_RES, THRESHOLD)

ig = pd.read_csv(IG_RES).query("method == 'ig_ql'").drop_duplicates("member")[["member", "family", "gap_pct"]]
ils = pd.read_csv(ILS_RES).query("method == 'ils_ql'").drop_duplicates("member")[["member", "gap_pct"]]
df = (ig.rename(columns={"gap_pct": "ig"}).merge(ils.rename(columns={"gap_pct": "ils"}), on="member")
        .merge(holdout_dup_ratios(), on="member"))
df["chose_ig"] = df.dup_ratio > THRESHOLD
df["disp"] = np.where(df.chose_ig, df.ig, df.ils)
df["orc"] = np.minimum(df.ig, df.ils)


def row(label, g):
    d = g[g.ig != g.ils]
    acc = 100 * ((d.ig < d.ils) == d.chose_ig).mean()
    vals = [g.ig.mean(), g.ils.mean(), g.disp.mean(), g.orc.mean()]
    best = min(vals[:3])
    cells = []
    for k, v in enumerate(vals):
        t = f"{v:.3f}"
        cells.append(rf"\textbf{{{t}}}" if k < 3 and abs(v - best) < 1e-12 else t)
    return f"{label} & {len(g)} & {100 * (1 - g.chose_ig.mean()):.1f} & {acc:.1f} & " + " & ".join(cells) + r" \\"


lines = [
    "% Auto-generated by analysis/make_table_dispatch.py (Entrada 96)",
    r"\begin{table}[t]",
    r"\centering",
    (r"\caption{Held-out test of the one-feature dispatch rule (IG if $\mathrm{dup\_ratio}>0.1$, ILS otherwise; "
     r"threshold fixed before the test). ``ILS chosen'' is the share of instances sent to ILS; ``Acc.'' is the share "
     r"of instances, among those where the two methods differ, on which the rule picked the better one. Mean GAP "
     r"(\%) of always using \textsc{IG-QL}, always using \textsc{ILS-QL}, the rule, and the per-instance oracle "
     r"(minimum of the two). Bold: best of the three non-oracle policies.}"),
    r"\label{tab:f8_dispatch}",
    r"{\scriptsize\setlength{\tabcolsep}{4pt}",
    r"\begin{tabular}{@{}lrrrrrrr@{}}",
    r"\toprule",
    r"Family & $N$ & ILS chosen (\%) & Acc.\ (\%) & Always IG & Always ILS & Rule & Oracle \\",
    r"\midrule",
]
for fam in ["B", "C", "E"]:
    lines.append(row(fam, df[df.family == fam]))
lines += [r"\midrule", row("All", df), r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
out = ROOT / "paper" / "f8_dispatch.tex"
out.write_text("\n".join(lines), encoding="utf-8")
print("\n".join(lines[-12:]))
