"""Gera paper/s_taillard.tex (secao do suplemento: replicacao do flowshop em instancias classicas de Taillard, Entrada 159/160)
a partir de results/pfsp_taillard_entrada159.csv e results/entrada159_taillard_primary.csv.
Uso: python -m analysis.make_table_taillard
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
KEY = ["n", "m", "rep"]
rel = lambda a, b: 100.0 * (np.asarray(a, float) - np.asarray(b, float)) / np.asarray(b, float)


def fmt_p(p):
    return f"{p:.2f}" if p >= 0.01 else f"${p / 10 ** int(np.floor(np.log10(p))):.0f}\\times10^{{{int(np.floor(np.log10(p)))}}}$"


P = pd.read_csv(R / "entrada159_taillard_primary.csv")
d = pd.read_csv(R / "pfsp_taillard_entrada159.csv")
ch = json.loads((R / "pfsp_choice_entrada152.json").read_text())
w = d.pivot(index=KEY, columns="method", values="makespan").reset_index()
w["val"] = [r[f"ig_fix_{ch['d_val'][f'{int(r.n)}x{int(r.m)}']['action']}"] for _, r in w.iterrows()]
w["oracle"] = w[[f"ig_fix_{k}" for k in range(5)]].min(axis=1)

L = ["% Auto-generated by analysis/make_table_taillard.py (Entrada 159/160)",
     "\\section{Flowshop: replication on Taillard's classic instances}",
     "\\label{sec:m-taillard}",
     "",
     "The study of Section~\\ref{sec:pfsp} was repeated on $40$ classic instances of \\citet{Taillard1993}: ta041--ta050 ($50\\times10$), ta051--ta060 ($50\\times20$), ta071--ta080 ($100\\times10$) and ta081--ta090 ($100\\times20$). "
     "The instances were regenerated from the generator and the seeds published by Taillard (distributed by OR-Library, \\texttt{flowshop2.txt}, downloaded on 2026-10-18); the generator reproduces the verification matrix of ta001 printed with it, and the machine-based lower bound of ta001 equals the published one ($1232$). "
     "All settings were frozen from the study on generated instances (Entrada 152): the ten methods, $T=300$, the validated destruction size per size ($d=8,6,8,6$), the state thresholds and the CPU ratios that give the ILS and the IG without local search the CPU time of the IG. "
     "The family of five tests, the Holm correction over five and the decision rule are those of Entrada 152; the predictions were recorded before the run (Entrada 159).",
     "",
     "\\begin{table}[t]",
     "\\centering",
     "\\caption{Replication on $40$ classic Taillard instances. $\\bar d$ in \\% of the makespan (negative: first method better); Wilcoxon, Holm over five; ``confirmed'': $p_{\\mathrm{Holm}}<0.05$ and $\\bar d<0$. "
     "The IG without local search receives $T_{\\mathrm{eq}}$ iterations (realised CPU ratio $1.09$), the ILS $T_{\\mathrm{eq}}$ (ratio $1.06$).}",
     "\\label{tab:s_taillard}",
     "{\\scriptsize\\setlength{\\tabcolsep}{3.5pt}",
     "\\begin{tabular}{@{}lrrrrrr@{}}",
     "\\toprule",
     "Comparison & W/L/T & $\\bar d$ (\\%) & 90\\% interval & $p_{\\mathrm{Holm}}$ & Confirmed \\\\",
     "\\midrule"]
names = {"P1": "P1: IG vs ILS, equal CPU", "P2": "P2: IG with vs without local search, equal CPU", "P3": "P3: Q-Learning vs random $d$", "P4": "P4: validated $d$ vs Q-Learning", "P5": "P5: validated $d$ vs random $d$"}
for r in P.itertuples():
    L.append(f"{names[r.id]} & {r.better}/{r.worse}/{r.tie} & {r.mean_d_pct:+.3f} & [{r.ci90_lo:+.3f}, {r.ci90_hi:+.3f}] & {fmt_p(r.p_holm)} & {'yes' if r.confirmada else 'no'} \\\\")
L += ["\\bottomrule", "\\end{tabular}}", "\\end{table}", ""]
L += ["By size, the mean difference (\\%) of the validated size, of Q-Learning and of the per-instance oracle with respect to random choice of $d$, and of the IG with respect to the ILS and to the IG without local search: "]
rows = []
for (n, m), g in w.groupby(["n", "m"]):
    rows.append(f"${int(n)}\\times{int(m)}$ & {rel(g.val, g.ig_rand).mean():+.3f} & {rel(g.ig_ql, g.ig_rand).mean():+.3f} & {rel(g.oracle, g.ig_rand).mean():+.3f} & {rel(g.ig_rand, g.ils_eq).mean():+.3f} & {rel(g.ig_rand, g.ig_nols_eq).mean():+.3f} \\\\")
L += ["\\begin{table}[t]", "\\centering", "\\caption{Replication on Taillard's instances, by size ($10$ instances each): mean difference in \\% of the makespan (negative: first better).}", "\\label{tab:s_taillard_size}",
      "{\\scriptsize", "\\begin{tabular}{@{}lrrrrr@{}}", "\\toprule", "Size & validated vs random & Q-Learning vs random & oracle vs random & IG vs ILS & IG vs IG without LS \\\\", "\\midrule"] + rows + ["\\bottomrule", "\\end{tabular}}", "\\end{table}", ""]
L.append("Outcome of the pre-specified reading: the finding of the generated instances replicates (P1 not confirmed, P2 confirmed, P3 not confirmed, favourable sign for P4). With $40$ instances only P2 is confirmed individually; P4 has $p_{\\mathrm{Holm}}=0.064$. "
         "Of the predictions recorded before the run, all signs were right; the magnitude of P5 was not ($-0.11\\%$ against a prediction below $0.05\\%$ in absolute value).")
(ROOT / "paper" / "s_taillard.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
print("ok -> paper/s_taillard.tex")
