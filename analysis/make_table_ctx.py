"""Gera paper/f37_ctx.tex (tabela principal: aprendizes de outra classe no espaco 'tamanho de destruicao', Entrada 159/160)
a partir de results/entrada159_ctx_primary.csv e results/entrada159_ctx.txt.
Uso: python -m analysis.make_table_ctx
"""
from __future__ import annotations

import re
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
P = pd.read_csv(R / "entrada159_ctx_primary.csv")
txt = (R / "entrada159_ctx.txt").read_text(encoding="utf-8")
cap = {k: float(v) for k, v in re.findall(r"(val_ctx|linucb_d|ql_d|ucb_d|ql_d_pre|oracle) (-?\d+\.\d+)", txt.split("Razao de captura")[1].split("\n")[0])}


def fmt_p(p):
    if p >= 0.01:
        return f"{p:.2f}"
    e = int(np.floor(np.log10(p)))
    return f"${p / 10 ** e:.0f}\\times10^{{{e}}}$"


names = {"C1": "C1: offline selector vs validated per cell", "C2": "C2: offline selector vs random $d$",
         "C3": "C3: LinUCB vs random $d$", "C4": "C4: validated per cell vs LinUCB"}
L = ["% Auto-generated by analysis/make_table_ctx.py (Entrada 159/160)", "\\begin{table}[t]", "\\centering",
     "\\caption{Learners of other classes for the destruction size ($\\mathrm{R}||C_{\\max}$, standard benchmark, LP-IG, the $700$ test instances of Table~\\ref{tab:f33_dpolicy}, $T=1000$; design and predictions recorded beforehand). "
     "LinUCB: contextual bandit with linear function approximation (context: progress, stagnation and two solver features; $\\alpha=0.25$ chosen on $280$ tuning instances). "
     "Instance-conditional selector: $k$-nearest-neighbour regression on eight features of the time matrix (no instance type), trained offline on the same $280$ tuning instances and chosen by cross-validation among three models. "
     "$\\bar d$ in \\% of the makespan (negative: first better); Wilcoxon, Holm over four; confirmed: $p_{\\mathrm{Holm}}<0.05$ and $\\bar d<0$. Last row: gain over random $d$ as a fraction of the gain of the validated choice ($0.201\\%$).}",
     "\\label{tab:f37_ctx}", "{\\scriptsize\\setlength{\\tabcolsep}{3pt}", "\\begin{tabular}{@{}lrrrrl@{}}", "\\toprule",
     "Comparison & W/L/T & $\\bar d$ (\\%) & 90\\% interval & $p_{\\mathrm{Holm}}$ & Confirmed \\\\", "\\midrule"]
for r in P.itertuples():
    L.append(f"{names[r.id]} & {r.better}/{r.worse}/{r.tie} & {r.mean_d_pct:+.3f} & [{r.ci90_lo:+.3f}, {r.ci90_hi:+.3f}] & {fmt_p(r.p_holm)} & {'yes' if r.confirmada else 'no'} \\\\")
L += ["\\midrule", f"\\multicolumn{{6}}{{p{{0.95\\textwidth}}}}{{Capture of the validated gain: instance-conditional selector {cap['val_ctx']:.2f}; LinUCB {cap['linucb_d']:.2f}; UCB1 {cap['ucb_d']:.2f}; online Q-Learning {cap['ql_d']:.2f}; pre-trained Q-Learning {cap['ql_d_pre']:.2f}}} \\\\",
      "\\bottomrule", "\\end{tabular}}", "\\end{table}"]
(ROOT / "paper" / "f37_ctx.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
print("ok -> paper/f37_ctx.tex", cap)
