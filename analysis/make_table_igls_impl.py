kev = pd.read_csv(R / "entrada170_numba_k.csv")
rng = lambda d, key=None: (min((v["K"] if key is None else v[key]) for v in d.values()), max((v["K"] if key is None else v[key]) for v in d.values()))


def row(label, r, k):
    lo, hi = r.ci90_lo, r.ci90_hi
    n_ = f"{int(r.n):,}".replace(",", "{,}")
    return f"{label} & {n_} & {int(r.better)}/{int(r.worse)}/{int(r.tie)} & {r.mean_d_pct:+.3f} & [{lo:+.3f}, {hi:+.3f}] & {k} \\\\"


def span(x):
    return f"{x.min():.1f}--{x.max():.1f}"


