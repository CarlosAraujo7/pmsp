     row("\\quad equal CPU, vectorized implementation", p162.loc["D2"], f"{k_r_new[0]:.1f}--{k_r_new[1]:.1f}"),
     row("\\quad equal CPU, compiled implementation", p170.loc["C3"], f"{k_r_c[0]:.1f}--{k_r_c[1]:.1f}"),
