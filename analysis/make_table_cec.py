def reading(r, pos, neg, margin=0.05):
    """Leitura sob a regra de paridade: sem diferenca, paridade (IC dentro da margem) ou o sentido da diferenca."""
    if r.p_holm >= 0.05:
        return "no difference"
    if r.ci90_lo >= -margin and r.ci90_hi <= margin:
        return "parity"
    return pos if r.mean_d_pct > 0 else neg


