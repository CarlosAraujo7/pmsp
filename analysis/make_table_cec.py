    """Ganho em pontos percentuais (positivo: o primeiro braco e' melhor) = -d, com o intervalo de 90% espelhado."""
    return f"{-r.mean_d_pct:+.3f} [{-r.ci90_hi:+.3f}, {-r.ci90_lo:+.3f}]"


