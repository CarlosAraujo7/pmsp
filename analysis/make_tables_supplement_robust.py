# ---------------------------------------------------------------- d sweep
res = pd.read_csv(ROOT / "results" / "results.csv")
hyp = pd.read_csv(ROOT / "results" / "hyperparam_sensitivity_entrada105.csv")
cols = ["instance", "rep", "method", "gap_pct"]
d = pd.concat([res[res.method.isin(["ig_ql", "ig_random"]) & (res.rep < 50)][cols], hyp[cols]]).drop_duplicates(["instance", "rep", "method"])
cls_ = ["rand_20j_6m", "rand_50j_10m", "rand_75j_15m", "rand_100j_20m", "rand_150j_30m", "rand_300j_20m"]
d = d[d.instance.isin(cls_)]
L = ["% Auto-generated by analysis/make_tables_supplement_robust.py (Entrada 112)", r"\begin{table}[t]", r"\centering",
     (r"\caption{Mean GAP (\%) against the classical lower bound as a function of the destruction size $d/n$ (50 instances per class; $d=0.3n$ is the default "
      r"used throughout and was never tuned). Bold: best $d$ in each row for each method.}"),
     r"\label{tab:s_hyperd}", r"{\scriptsize\setlength{\tabcolsep}{4pt}", r"\begin{tabular}{@{}lrrrrrrrr@{}}", r"\toprule",
     r" & \multicolumn{4}{c}{\texttt{ig\_ql}} & \multicolumn{4}{c}{\texttt{ig\_random}} \\", r"\cmidrule(lr){2-5}\cmidrule(lr){6-9}",
     r"Class & 0.1 & 0.2 & 0.3 & 0.4 & 0.1 & 0.2 & 0.3 & 0.4 \\", r"\midrule"]
for c in cls_:
    n, m = c.split("_")[1][:-1], c.split("_")[2][:-1]
    row = []
    for base in ["ig_ql", "ig_random"]:
        v = [d[(d.instance == c) & (d.method == mm)].gap_pct.mean() for mm in [f"{base}_d10", f"{base}_d20", base, f"{base}_d40"]]
        b = min(round(x, 3) for x in v)
        row += [(r"\textbf{%.3f}" if round(x, 3) == b else "%.3f") % x for x in v]
    L.append(f"$({n},{m})$ & " + " & ".join(row) + r" \\")
L += [r"\bottomrule", r"\end{tabular}}", r"\end{table}"]
write("s_hyper_d.tex", L)
