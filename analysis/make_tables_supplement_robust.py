"""
analysis/make_tables_supplement_robust.py (Entrada 112)
Gera as tabelas do suplemento (paper/s_*.tex) a partir dos CSV das Entradas 104-110:
  s_seed_variance.tex    ICC e SD intra-instancia (Entrada 109)
  s_new_distributions.tex GAP/otimalidade por distribuicao (Entrada 108)
  s_equal_cpu.tex        testes E1-E4 (Entrada 110)
  s_hyper_d.tex          GAP medio por fracao de destruicao d (Entrada 105)
Uso: python -m analysis.make_tables_supplement_robust
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
OUT = ROOT / "paper"
TT = {"ig_ql": r"\texttt{ig\_ql}", "ig_random": r"\texttt{ig\_random}", "ils_ql": r"\texttt{ils\_ql}", "ils_random": r"\texttt{ils\_random}"}


def write(name, lines):
    (OUT / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {name}")


def icc(g, col):
    k = g.groupby("rep")[col].size().mean()
    msb = g.groupby("rep")[col].mean().var(ddof=1) * k
    msw = g.groupby("rep")[col].var(ddof=1).mean()
    return float((msb - msw) / (msb + (k - 1) * msw))


# ---------------------------------------------------------------- seed variance
sv = pd.concat([pd.read_csv(ROOT / "results" / "seed_variance_entrada109.csv"), pd.read_csv(ROOT / "results" / "seed_variance_all_entrada117.csv")])
L = ["% Auto-generated by analysis/make_tables_supplement_robust.py (Entrada 112)", r"\begin{table}[t]", r"\centering",
     (r"\caption{Seed variance (20 instances $\times$ 10 algorithm seeds per class). Mean GAP (\%), share of the GAP variance explained by the "
      r"instance (ICC) and mean within-instance standard deviation of the GAP (percentage points).}"),
     r"\label{tab:s_seed}", r"{\scriptsize\setlength{\tabcolsep}{4pt}", r"\begin{tabular}{@{}lrrrrrrrrrrrr@{}}", r"\toprule",
     r" & \multicolumn{3}{c}{\texttt{ig\_ql}} & \multicolumn{3}{c}{\texttt{ig\_random}} & \multicolumn{3}{c}{\texttt{ils\_ql}} & \multicolumn{3}{c}{\texttt{ils\_random}} \\",
     r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}\cmidrule(lr){11-13}",
     r"Class & GAP & ICC & SD & GAP & ICC & SD & GAP & ICC & SD & GAP & ICC & SD \\", r"\midrule"]
for cls in sorted(sv.instance.unique(), key=lambda c: int(c.split("_")[1][:-1])):
    n, m = cls.split("_")[1][:-1], cls.split("_")[2][:-1]
    cells = []
    for mt in ["ig_ql", "ig_random", "ils_ql", "ils_random"]:
        g = sv[(sv.instance == cls) & (sv.method == mt)]
        cells += [f"{g.gap_pct.mean():.3f}", f"{icc(g, 'gap_pct'):.2f}", f"{g.groupby('rep').gap_pct.std(ddof=1).mean():.3f}"]
    L.append(f"$({n},{m})$ & " + " & ".join(cells) + r" \\")
L += [r"\bottomrule", r"\end{tabular}}", r"\end{table}"]
write("s_seed_variance.tex", L)

# ---------------------------------------------------------------- new distributions
nd = pd.read_csv(ROOT / "results" / "new_distributions_entrada108.csv")
ex = pd.read_csv(ROOT / "results" / "new_distributions_entrada108_exact.csv")
key = ["dist", "n", "m", "rep"]
w = nd.pivot(index=key, columns="method", values="makespan").reset_index().merge(nd.drop_duplicates(key)[key + ["dup_ratio"]], on=key).merge(ex[key + ["lb_lp"]], on=key)
names = {"u1_100": r"$U[1,100]$", "u50_100": r"$U[50,100]$", "u1_10000": r"$U[1,10^4]$", "lognormal": "Log-normal", "bimodal": "Bimodal", "pareto": "Pareto"}
order = ["u1_100", "u50_100", "u1_10000", "lognormal", "bimodal", "pareto"]
ms = ["multifit", "ldm", "ig_ql", "ils_ql", "ig_ql_seed"]
lab = {"multifit": r"\textsc{MultiFit}", "ldm": r"\textsc{LDM}", "ig_ql": r"\textsc{IG-QL}", "ils_ql": r"\textsc{ILS-QL}", "ig_ql_seed": r"\textsc{IG-QL}$^{+}$"}
L = ["% Auto-generated by analysis/make_tables_supplement_robust.py (Entrada 112)", r"\begin{table}[t]", r"\centering",
     (r"\caption{New processing-time distributions (30 instances $\times$ 5 sizes = 150 per distribution). Mean GAP (\%) against the best lower bound "
      r"available (certified arc-flow bound; classical improved bound when the arc-flow graph exceeded $4\times10^5$ arcs, mostly $U[1,10^4]$), and, in "
      r"parentheses, the share of provably optimal solutions (\%). ``Dup.'' is the share of instances with duplicate ratio $>0.1$.}"),
     r"\label{tab:s_newdist}", r"{\scriptsize\setlength{\tabcolsep}{3.5pt}", r"\begin{tabular}{@{}lr" + "r" * len(ms) + r"@{}}", r"\toprule",
     "Distribution & Dup. (\\%) & " + " & ".join(lab[k] for k in ms) + r" \\", r"\midrule"]
for dname in order:
    g = w[w.dist == dname]
    cells = []
    gaps = [100 * ((g[k] - g.lb_lp) / g.lb_lp).mean() for k in ms]
    best = min(round(x, 3) for x in gaps)
    for k, gp in zip(ms, gaps):
        s = f"{gp:.3f}"
        if round(gp, 3) == best:
            s = r"\textbf{" + s + "}"
        cells.append(f"{s} ({100 * (g[k] == g.lb_lp).mean():.0f})")
    L.append(f"{names[dname]} & {100 * (g.dup_ratio > 0.1).mean():.0f} & " + " & ".join(cells) + r" \\")
L += [r"\bottomrule", r"\end{tabular}}", r"\end{table}"]
write("s_new_distributions.tex", L)

# ---------------------------------------------------------------- equal cpu
