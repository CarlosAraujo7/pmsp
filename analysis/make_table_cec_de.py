"""
analysis/make_table_cec_de.py (Entrada 291)
=============================================
Gera cec/tab_de.tex: o ganho mediano sobre o aleatorio (decadas) dos sete aprendizes no hospedeiro de evolucao diferencial, por credito (sucesso, log_incumbent, rel_incumbent), com o numero de funcoes em que o ganho e'
negativo. Fonte: results/entrada291_summary.csv (analysis/report_entrada291_credit.py). Uso: python -m analysis.make_table_cec_de
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
S = pd.read_csv(ROOT / "results" / "entrada291_summary.csv")
NAMES = {"ql_std": "Q-Learning, first max.", "ql_rt": "Q-Learning, random ties", "ucb": "UCB1", "pg": "Policy gradient", "pm": "Prob. matching", "ap": "Adaptive pursuit", "etc": "Explore-then-commit"}
ORDER = ["ql_std", "ql_rt", "ucb", "pg", "pm", "ap", "etc"]
CRED = ["success", "log_incumbent", "rel_incumbent"]


def gfmt(v):
    return "$0.00$" if abs(v) < 0.005 else f"${v:+.2f}$"


rows = []
for m in ORDER:
    cells = [NAMES[m]]
    for c in CRED:
        r = S[(S.credito == c) & (S.aprendiz == m)].iloc[0]
        cells += [gfmt(r.mediana_ganho), f"${int(r.neg)}$"]
    rows.append(" & ".join(cells) + r" \\")
tex = r"""% Auto-generated by analysis/make_table_cec_de.py (results/entrada291_summary.csv)
\begin{table}[t]
\caption{Differential evolution on the 24 BBOB functions ($D=10$, five strategies): median gain over random choice, in decades of the final error (positive is better), and the number of functions, out of $24$, where it is negative, by credit assignment. The strategy validated per function gains up to $8.4$ decades. $^{\dagger}$Uses the optimum value $f_{\rm opt}$: an upper bound on an aligned credit, not a practical method.}
\label{tab:de}
\centering
{\scriptsize\setlength{\tabcolsep}{2.2pt}
\begin{tabular}{@{}lrrrrrr@{}}
\toprule
 & \multicolumn{2}{c}{Success rate} & \multicolumn{2}{c}{Log-incumbent$^{\dagger}$} & \multicolumn{2}{c}{Rel. incumbent} \\
Learner & gain & $<0$ & gain & $<0$ & gain & $<0$ \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}}
\end{table}
"""
(ROOT / "cec" / "tab_de.tex").write_text(tex, encoding="utf-8")
print("cec/tab_de.tex written")
