"""Gera paper/f40_online_replic.tex (LinUCB e Q-learning neural online nos ambientes P||Cmax e flowshop; Entrada 167/168) a partir de results/entrada167_online_primary.csv e entrada167_online.txt.
Uso: python -m analysis.make_table_online
"""
from __future__ import annotations

import re
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
P = pd.read_csv(R / "entrada167_online_primary.csv")


def fmt_p(p):
    if p >= 0.01:
        return f"{p:.2f}"
    e = int(np.floor(np.log10(p)))
    return f"${p / 10 ** e:.0f}\\times10^{{{e}}}$"


lab = {"G1": "LinUCB vs random $d$", "G2": "neural Q-learning vs random $d$", "G3": "validated $d$ vs LinUCB", "G4": "validated $d$ vs neural Q-learning"}
env_name = {"P": "P$||C_{\\max}$ ($1{,}200$ instances, $T=1000$)", "F": "Flowshop ($160$ instances: $120$ generated, $40$ Taillard; $T=300$)"}
L = ["% Auto-generated by analysis/make_table_online.py (Entrada 167/168)", "\\begin{table}[t]", "\\centering",
     "\\caption{The contextual bandit (LinUCB) and the neural Q-learner choosing the destruction size in the two other problems (same instances, seeds, actions and baselines as before; hyperparameters chosen on tuning instances of each problem; design and predictions recorded beforehand). "
     "$\\bar d$ in \\% of the makespan (negative: first better); Wilcoxon, Holm over four within each problem; confirmed: $p_{\\mathrm{Holm}}<0.05$ and $\\bar d<0$ (the neural learner is significantly \\emph{worse} than random choice in the flowshop: $\\bar d>0$).}",
     "\\label{tab:f40_online}", "{\\scriptsize\\setlength{\\tabcolsep}{3pt}", "\\begin{tabular}{@{}lrrrrl@{}}", "\\toprule", "Comparison & W/L/T & $\\bar d$ (\\%) & 90\\% interval & $p_{\\mathrm{Holm}}$ & Confirmed \\\\", "\\midrule"]
for env in ("P", "F"):
    L.append(f"\\multicolumn{{6}}{{l}}{{{env_name[env]}}} \\\\")
    for g in ("G1", "G2", "G3", "G4"):
        r = P[P.id == f"{env}-{g}"].iloc[0]
        L.append(f"\\quad {lab[g]} & {int(r.better)}/{int(r.worse)}/{int(r.tie)} & {r.mean_d_pct:+.3f} & [{r.ci90_lo:+.3f}, {r.ci90_hi:+.3f}] & {fmt_p(r.p_holm)} & {'yes' if r.confirmada else 'no'} \\\\")
    if env == "P":
        L.append("\\midrule")
L += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
(ROOT / "paper" / "f40_online_replic.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
print("ok -> paper/f40_online_replic.tex")
