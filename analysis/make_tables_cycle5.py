def fmt_p(p):
    if p != p:
        return "--"
    if p < 1e-300:
        return "$<10^{-300}$"
    if p >= 0.001:
        return f"{p:.3f}"
    e = int(np.floor(np.log10(p)))
    mant = round(p / 10 ** e)
    if mant == 10:
        mant, e = 1, e + 1
    return f"${mant}\\times10^{{{e}}}$"


def write(name, lines):
    (OUT / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", name)


