def build_summary_df(df):
    grp = df.groupby(["method", "n", "m"])
    summary = grp.agg(
        gap_mean  = ("gap_pct",  "mean"),
        gap_std   = ("gap_pct",  "std"),
        time_mean = ("cpu_time", "mean"),
        time_std  = ("cpu_time", "std"),
        n_reps    = ("rep",      "count"),
    ).reset_index()
    method_rank = {m: i for i, m in enumerate(METHOD_ORDER)}
    summary["_rank"] = summary["method"].map(method_rank)
    summary = summary.sort_values(["n", "m", "_rank"]).drop(columns="_rank")
    return summary


def print_summary(df):
    summary = build_summary_df(df)
    prev_size = None
    for _, row in summary.iterrows():
        size = (row.n, row.m)
        if size != prev_size:
            print(f"\n--- n={row.n}, m={row.m} ---")
            hdr = f"{'Method':<14} {'GAP% mean':>10} {'GAP% std':>10} {'Time mean':>10} {'Time std':>10}"
            print(hdr)
            prev_size = size
        print(f"{row.method:<14} {row.gap_mean:>10.4f} {row.gap_std:>10.4f} {row.time_mean:>10.4f} {row.time_std:>10.4f}")


def latex_results_table(df, out_path, label="tab:results"):
    caption = ("Computational results: mean GAP(\\%) and CPU time (s) over 30"
               " independent runs. Best ILS result in each row is highlighted in bold.")
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    summary     = build_summary_df(df)
    ils_methods = [m for m in METHOD_ORDER[1:] if m in df["method"].unique()]
    all_methods = [m for m in METHOD_ORDER      if m in df["method"].unique()]
    col_spec    = "rr" + "S[table-format=2.2]" * (len(all_methods) + len(ils_methods))
    L = ["% Auto-generated by analysis/tables.py",
         r"\begin{table*}[t]", r"\centering",
         "\\caption{" + caption + "}",
         "\\label{" + label + "}",
         "\\begin{tabular}{" + col_spec + "}",
         r"\toprule"]
    gh = " & ".join("\\multicolumn{1}{c}{" + METHOD_LABELS_LATEX.get(m,m) + " GAP(\\%)}" for m in all_methods)
    th = " & ".join("\\multicolumn{1}{c}{" + METHOD_LABELS_LATEX.get(m,m) + " $t$(s)}" for m in ils_methods)
    L.append("\\multicolumn{1}{c}{$n$} & \\multicolumn{1}{c}{$m$} & " + gh + " & " + th + " \\\\")
    L.append(r"\midrule")
    prev_n = None
    for (n_val, m_val), group in summary.groupby(["n", "m"]):
        if prev_n is not None and n_val != prev_n:
            L.append(r"\midrule")
        prev_n = n_val
        rd = {r["method"]: r for _, r in group.iterrows()}
        ig = {m: rd[m]["gap_mean"] for m in ils_methods if m in rd}
        best = min(ig, key=ig.get) if ig else None
        gc = []
        for m in all_methods:
            if m not in rd: gc.append("{--}")
            else:
                v = f"{rd[m]['gap_mean']:.2f}"
                if m == best: v = "\\bfseries " + v
                gc.append(v)
        tc = [f"{rd[m]['time_mean']:.2f}" if m in rd else "{--}" for m in ils_methods]
        L.append(str(n_val) + " & " + str(m_val) + " & " + " & ".join(gc) + " & " + " & ".join(tc) + " \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
    out_path.write_text("\n".join(L) + "\n", encoding="utf-8")
    return out_path


def latex_wilcoxon_table(df, out_path, alpha=0.05, label="tab:wilcoxon"):
    caption = ("Wilcoxon signed-rank test $p$-values for pairwise comparison of"
               " \\textsc{ILS-QL} against the other ILS variants."
               " Bold: $p < 0.05$. $\\downarrow$ = ILS-QL better;"
               " $\\uparrow$ = ILS-QL worse; \\textit{tie} = all 30 pairs identical.")
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    ils_others = [m for m in ["ils_random","ils_ucb","ils_rf","ils_rand_hi","ils_ql_ws","ils_ql_hi"] if m in df["method"].unique()]
    if "ils_ql" not in df["method"].unique() or not ils_others:
        out_path.write_text("% ILS-QL not present.\n", encoding="utf-8")
        return out_path
    sizes = df[["n","m"]].drop_duplicates().sort_values(["n","m"])
    col_spec = "rr" + "c" * len(ils_others)
    hdrs = " & ".join("\\multicolumn{1}{c}{\\textsc{ILS-QL} vs " + METHOD_LABELS_LATEX.get(m,m) + "}" for m in ils_others)
    L = ["% Auto-generated by analysis/tables.py",
         r"\begin{table}[t]", r"\centering",
         "\\caption{" + caption + "}",
         "\\label{" + label + "}",
         "\\begin{tabular}{" + col_spec + "}",
         r"\toprule",
         "$n$ & $m$ & " + hdrs + " \\\\",
         r"\midrule"]
    prev_n = None
    for _, sz in sizes.iterrows():
        n_val = int(sz["n"])
        m_val = int(sz["m"])
        if prev_n is not None and n_val != prev_n:
            L.append(r"\midrule")
        prev_n = n_val
        cells = []
        for meth in ils_others:
            sub_m  = df[(df["method"]==meth)      & (df["n"]==n_val) & (df["m"]==m_val)]
            sub_ql = df[(df["method"]=="ils_ql")  & (df["n"]==n_val) & (df["m"]==m_val)]
            merged = pd.merge(
                sub_ql[["rep","gap_pct"]].rename(columns={"gap_pct":"ql"}),
                sub_m[["rep","gap_pct"]].rename(columns={"gap_pct":"other"}),
                on="rep")
            if len(merged) < 3:
                cells.append("{N/A}")
                continue
            diffs = merged["ql"] - merged["other"]
            if (diffs == 0).all():
                cells.append(r"\textit{tie}")
                continue
            with _warnings.catch_warnings():
                _warnings.simplefilter("ignore")
                stat, p = stats.wilcoxon(merged["ql"], merged["other"],
                                         alternative="two-sided", zero_method="wilcox")
            if p != p:
                cells.append(r"\textit{tie}")
                continue
            direction = r"$\downarrow$" if merged["ql"].mean() < merged["other"].mean() else r"$\uparrow$"
            p_str = f"{p:.4f}"
            if p < alpha:
                p_str = "\\textbf{" + p_str + "} " + direction
            cells.append(p_str)
        L.append(str(n_val) + " & " + str(m_val) + " & " + " & ".join(cells) + " \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    out_path.write_text("\n".join(L) + "\n", encoding="utf-8")
    return out_path


def latex_improvement_table(df, out_path, label="tab:improvement"):
    """
    Generates a LaTeX table with two complementary metrics per method:

      1. %Opt  : percentage of 30 runs that achieved GAP = 0 (reached lower bound)
      2. Delta : mean absolute improvement in GAP(%) over LPT
                 Delta_m = mean_GAP_LPT(n,m) - mean_GAP_method(n,m)

    LPT is the reference; its own Delta column is shown as "--".
    """
    caption = (
        "Percentage of runs reaching the lower bound (\\%Opt) and mean GAP(\\%) "
        "improvement over \\textsc{LPT} ($\\Delta$) for each method and instance size. "
        "Bold: best \\%Opt or largest $\\Delta$ among ILS variants per row."
    )
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    all_methods = [m for m in METHOD_ORDER if m in df["method"].unique()]
    ils_methods = [m for m in METHOD_ORDER[1:] if m in df["method"].unique()]

    summary = build_summary_df(df)
    _pct = (
        df.groupby(["method", "n", "m"])["gap_pct"]
        .apply(lambda s: 100.0 * (s == 0).mean())
    )
    _pct.name = "pct_opt"
    opt_df = _pct.reset_index()
    merged = summary.merge(opt_df, on=["method", "n", "m"], how="left")

    col_spec = "rr" + "S[table-format=3.1]" * len(all_methods) + "S[table-format=2.2]" * len(ils_methods)

    L = [
        "% Auto-generated by analysis/tables.py",
        r"\begin{table*}[t]", r"\centering",
        "\\caption{" + caption + "}",
        "\\label{" + label + "}",
        "\\begin{tabular}{" + col_spec + "}",
        r"\toprule",
    ]
    opt_hdr = " & ".join(
        "\\multicolumn{1}{c}{" + METHOD_LABELS_LATEX.get(m, m) + " \\%Opt}"
        for m in all_methods
    )
    delta_hdr = " & ".join(
        "\\multicolumn{1}{c}{" + METHOD_LABELS_LATEX.get(m, m) + " $\\Delta$}"
        for m in ils_methods
    )
    L.append(
        "\\multicolumn{1}{c}{$n$} & \\multicolumn{1}{c}{$m$} & "
        + opt_hdr + " & " + delta_hdr + " \\\\"
    )
    L.append(r"\midrule")

    sizes = merged[["n", "m"]].drop_duplicates().sort_values(["n", "m"])
    prev_n = None
    for _, sz in sizes.iterrows():
        n_val = int(sz["n"])
        m_val = int(sz["m"])
        if prev_n is not None and n_val != prev_n:
            L.append(r"\midrule")
        prev_n = n_val
        row_data = {
            r["method"]: r
            for _, r in merged[(merged["n"] == n_val) & (merged["m"] == m_val)].iterrows()
        }
        lpt_gap = row_data["lpt"]["gap_mean"] if "lpt" in row_data else None
        ils_opts = {m: row_data[m]["pct_opt"] for m in ils_methods if m in row_data}
        best_opt = max(ils_opts, key=ils_opts.get) if ils_opts else None
        if lpt_gap is not None:
            ils_deltas = {m: lpt_gap - row_data[m]["gap_mean"] for m in ils_methods if m in row_data}
            best_delta = max(ils_deltas, key=ils_deltas.get) if ils_deltas else None
        else:
            ils_deltas = {}
            best_delta = None
        opt_cells = []
        for m in all_methods:
            if m not in row_data:
                opt_cells.append("{--}")
            else:
                v = f"{row_data[m]['pct_opt']:.1f}"
                if m == best_opt:
                    v = "\\bfseries " + v
                opt_cells.append(v)
        delta_cells = []
        for m in ils_methods:
            if m not in row_data or lpt_gap is None:
                delta_cells.append("{--}")
            else:
                d = lpt_gap - row_data[m]["gap_mean"]
                v = f"{d:.2f}"
                if m == best_delta:
                    v = "\\bfseries " + v
                delta_cells.append(v)
        L.append(
            str(n_val) + " & " + str(m_val)
            + " & " + " & ".join(opt_cells)
            + " & " + " & ".join(delta_cells)
            + " \\\\"
        )
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
    out_path.write_text("\n".join(L) + "\n", encoding="utf-8")
    return out_path



