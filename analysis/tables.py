def latex_wilcoxon_family_table(fam_df, out_path, reference_label,
                                 other_labels=None, alpha=0.05,
                                 caption=None, label="tab:wilcoxon_family"):
    """
    Gera tabela LaTeX a partir do DataFrame retornado por
    analysis.stats.pairwise_wilcoxon_family -- UMA familia por chamada
    (fam_df deve conter uma unica familia; passe o resultado ja filtrado
    se pairwise_wilcoxon_family foi chamada uma vez por familia, como em
    analysis/report_entrada37_sota_and_holm.py).

    Cada celula mostra: p_holm (negrito se reject_holm), seta de direcao
    ($\\downarrow$ = referencia melhor, $\\uparrow$ = referencia pior) e o
    effect size (correlacao rank-biserial pareada) entre parenteses em
    fonte menor -- ex.: "\\textbf{0.0012}$\\downarrow$ {\\scriptsize(0.71)}".
    Casos especiais: 'tie' (todos os pares identicos) e 'N/A' (menos de
    3 pares validos) seguem a mesma convencao textual da tabela antiga
    (latex_wilcoxon_table), para nao introduzir uma notacao nova no
    artigo sem necessidade.

    Parametros
    ----------
    fam_df : DataFrame
        Saida de pairwise_wilcoxon_family para UMA familia (colunas:
        other, n, m, n_pairs, p_holm, reject_holm, rank_biserial,
        direction, ...).
    out_path : Path ou str
    reference_label : str
        Rotulo LaTeX do metodo de referencia (ex.: "\\textsc{IG-QL}"),
        usado na legenda e no cabecalho das colunas.
    other_labels : dict, opcional
        Mapa {nome_interno: rotulo_latex} para os metodos comparados.
        Se None, usa METHOD_LABELS_LATEX (definido acima neste arquivo)
        como fallback, e o proprio nome se nao encontrado ali.
    alpha : float
        Usado so para a legenda (o dataframe ja traz reject_holm pronto).
    caption, label : str

    Retorna out_path (Path).
    """
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    if other_labels is None:
        other_labels = METHOD_LABELS_LATEX

    others = list(dict.fromkeys(fam_df["other"]))  # preserva ordem, remove dup
    sizes = fam_df[["n", "m"]].drop_duplicates().sort_values(["n", "m"])

    if caption is None:
        caption = (
            f"Wilcoxon signed-rank test ($p$-values adjusted by "
            f"Holm-Bonferroni) and effect size (paired rank-biserial "
            f"correlation, in parentheses) for {reference_label} against "
            f"each competing method. Bold: $p_{{\\mathrm{{holm}}}} < "
            f"{alpha}$. $\\downarrow$ = {reference_label} better; "
            f"$\\uparrow$ = {reference_label} worse; \\textit{{tie}} = all "
            f"pairs identical; N/A = fewer than 3 valid pairs."
        )

    col_spec = "rr" + "c" * len(others)
    hdrs = " & ".join(
        "\\multicolumn{1}{c}{" + reference_label + " vs " +
        other_labels.get(m, m) + "}" for m in others
    )
    wide = len(others) >= 6  # F1 (8 colunas) precisa; F2/F3/F4 (<=4) nao
    L = ["% Auto-generated by analysis/tables.py::latex_wilcoxon_family_table (Entrada 75)",
         r"\begin{table}[t]", r"\centering",
         "\\caption{" + caption + "}",
         "\\label{" + label + "}",
         r"{\scriptsize\setlength{\tabcolsep}{3pt}"]
    if wide:
        L.append(r"\resizebox{\textwidth}{!}{%")
    L += ["\\begin{tabular}{" + col_spec + "}",
          r"\toprule",
          "$n$ & $m$ & " + hdrs + " \\\\",
          r"\midrule"]

    prev_n = None
    for _, sz in sizes.iterrows():
        n_val, m_val = int(sz["n"]), int(sz["m"])
        if prev_n is not None and n_val != prev_n:
            L.append(r"\midrule")
        prev_n = n_val
        cells = []
        for other in others:
            row = fam_df[(fam_df["other"] == other) & (fam_df["n"] == n_val) & (fam_df["m"] == m_val)]
            if row.empty:
                cells.append("{--}")
                continue
            r = row.iloc[0]
            n_pairs = int(r["n_pairs"]) if pd.notna(r["n_pairs"]) else 0
            p_holm = r["p_holm"]
            if n_pairs < 3:
                cells.append("{N/A}")
                continue
            if pd.isna(p_holm):
                cells.append(r"\textit{tie}")
                continue
            direction = r"$\downarrow$" if r["direction"] == "ref_better" else r"$\uparrow$"
            rb = r["rank_biserial"]
            rb_str = f"{rb:.2f}" if pd.notna(rb) else "n/a"
            p_str = f"{p_holm:.4f}"
            if bool(r["reject_holm"]):
                p_str = "\\textbf{" + p_str + "}"
            cells.append(p_str + direction + " {\\scriptsize(" + rb_str + ")}")
        L.append(str(n_val) + " & " + str(m_val) + " & " + " & ".join(cells) + " \\\\")

    closing = r"\end{tabular}}}" if wide else r"\end{tabular}}"
    L += [r"\bottomrule", closing, r"\end{table}"]
    out_path.write_text("\n".join(L) + "\n", encoding="utf-8")
    return out_path


def generate_all_tables(df, out_dir):
    """Generates all LaTeX tables. Returns list of paths."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    paths.append(latex_results_table(df, out_dir / "results_table.tex"))
    paths.append(latex_wilcoxon_table(df, out_dir / "wilcoxon_table.tex"))
    paths.append(latex_improvement_table(df, out_dir / "improvement_table.tex"))
    return paths
