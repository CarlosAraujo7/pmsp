"""
analysis/make_tables_cycle3.py (Entrada 125)
Tabelas LaTeX do Ciclo 3 a partir dos CSV pre-registrados:
  paper/f20_budget_law.tex       lei do orcamento (Entrada 121, frente 1): politica e folga por T + testes B1-B4
  paper/f21_dsel_budget.tex      acoes d com T=5000 e pre-treino (frente 2): testes D1-D4
  paper/f22_igcv_seed.tex        IG ajustado + semeado (frente 4): testes E1-E4 + otimalidade provada
  paper/f23_unrelated_budget.tex R||Cmax: orcamento, CPU igual, MILP (frente 3): testes RB1-RB4
Uso: python -m analysis.make_tables_cycle3
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
OUT = ROOT / "paper"


def fmt_p(p):
    if p != p:
        return "--"
    if p < 1e-300:
        return "$<10^{-300}$"
    if p >= 0.001:
        return f"{p:.3f}"
    e = int(np.floor(np.log10(p)))
    return f"${p / 10 ** e:.0f}\\times10^{{{e}}}$"


def write(name, lines):
    (OUT / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", name)


def head(caption, label, cols, spec):
    return ["% Auto-generated by analysis/make_tables_cycle3.py (Entrada 125)", r"\begin{table}[t]", r"\centering", r"\caption{" + caption + "}", r"\label{" + label + "}",
            r"{\scriptsize\setlength{\tabcolsep}{3.5pt}", r"\begin{tabular}{@{}" + spec + r"@{}}", r"\toprule", cols + r" \\", r"\midrule"]


tail = [r"\bottomrule", r"\end{tabular}}", r"\end{table}"]

# ---------------------------------------------------------------- f20 budget law
txt = (ROOT / "results" / "entrada121_budget_law.txt").read_text(encoding="utf-8")
pooled = {}
for T in (100, 250, 1000):
    m = re.search(rf"T=\s*{T}: politica ig_ql_cal d = ([+-][0-9.]+)% IC90 \[([+-][0-9.]+), ([+-][0-9.]+)\] \| folga oraculo d = ([+-][0-9.]+)%", txt)
    pooled[T] = tuple(float(x) for x in m.groups())
F = pd.read_csv(ROOT / "results" / "entrada121_budget_law_primary.csv")
L = head(r"Budget law in $\mathrm{P}||C_{\max}$: policy effect (informative state, \texttt{ig\_ql\_cal} vs.\ \texttt{ig\_random}) and headroom of the three destruction strategies "
         r"(omniscient per-instance choice vs.\ random) as the budget $T$ shrinks (12 classes $\times$ 100 instances; 90\% bootstrap intervals). "
         r"Last rows: pre-specified tests (Holm over four): B1, B2 policy effect at $T=100$ and $250$; B3 policy effect, $T=100$ vs.\ $1000$ (12 class pairs); "
         r"B4 headroom, $T=100$ vs.\ $1000$.", "tab:f20_budget", r"$T$ & Policy $\bar d$ (\%) & 90\% interval & Headroom $\bar d$ (\%) & Capture", r"rrrrr")
for T in (100, 250, 1000):
    pol, lo, hi, hr = pooled[T]
    L.append(f"{T} & {pol:+.3f} & [{lo:+.3f}, {hi:+.3f}] & {hr:+.3f} & {pol / hr:.2f} \\\\")
L.append(r"\midrule")
for r in F.itertuples():
    desc = {"B1": r"B1: policy at $T=100$", "B2": r"B2: policy at $T=250$", "B3": r"B3: policy, $T=100$ vs.\ $1000$", "B4": r"B4: headroom, $T=100$ vs.\ $1000$"}[r.id]
    val = f"{r.mean_d_pct:+.3f}" if r.id in ("B1", "B2") else f"{r.mean_diff:+.3f}"
    L.append(f"\\multicolumn{{2}}{{l}}{{{desc}}} & {val} & & $p_{{\\mathrm{{Holm}}}}={fmt_p(r.p_holm)}$ \\\\")
write("f20_budget_law.tex", L + tail)

# ---------------------------------------------------------------- f21 dsel budget
