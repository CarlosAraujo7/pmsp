"""
analysis/make_table_gap_to_iaf.py
===================================
Gera paper/f5_gap_to_iaf_reference.tex: gap medio em relacao a solucao
EXATA de referencia (iAF) nas familias externas C e F, apenas nas
instancias com otimalidade provada pela planilha (Gap = 0). Mesmo estilo
das tabelas f1-f4. Entrada 90, item 4.

Depende de iaf_reference.csv (join verificado) e da amostra de
manifest.csv. Uso: python -m analysis.make_table_gap_to_iaf
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
EXT = ROOT / "external_benchmarks" / "pcmax_symmetry2025"

ref = pd.read_csv(EXT / "iaf_reference.csv")
man = pd.read_csv(EXT / "manifest.csv")
res = pd.read_csv(EXT / "results_external_symmetry2025.csv").drop_duplicates(["member", "method"])
res = res[res.member.isin(set(man.member))]
df = res.merge(ref[["member", "Z", "gap_sheet"]], on="member")
df = df[df.gap_sheet == 0].copy()
df["gap_opt"] = 100.0 * (df.makespan - df.Z) / df.Z
df["is_opt"] = df.makespan <= df.Z

METHODS = [("lpt", r"\textsc{LPT}"), ("multifit", r"\textsc{MultiFit}"),
           ("sa_li_perkins", r"\textsc{SA (Li\&Perkins)}"), ("bco", r"\textsc{BCO}"),
           ("ils_ql", r"\textsc{ILS-QL}"), ("ig_random", r"\textsc{IG-Random}"), ("ig_ql", r"\textsc{IG-QL}")]
FAMS = ["C", "F"]
stat = {}
for fam in FAMS:
    g = df[df.family == fam]
    for key, _ in METHODS:
        s = g[g.method == key]
        stat[(fam, key)] = (s.gap_opt.mean(), 100 * s.is_opt.mean(), s.gap_pct.mean())
nfam = {fam: df[df.family == fam].member.nunique() for fam in FAMS}

best = {}
for fam in FAMS:
    for j, better in enumerate([min, max, min]):
        best[(fam, j)] = better(stat[(fam, k)][j] for k, _ in METHODS)

lines = [
    "% Auto-generated by analysis/make_table_gap_to_iaf.py (Entrada 90)",
    r"\begin{table}[t]",
    r"\centering",
    (r"\caption{Mean gap to the exact reference solution (iAF; \citealp{OstojicEtAl2025}) on the external "
     rf"families C ($N={nfam['C']}$) and F ($N={nfam['F']}$), restricted to instances whose optimality the "
     r"reference proves. ``Opt.'' is the share of instances solved to the reference value; ``GAP$_{\mathrm{LB}}$'' "
     r"is the gap to the classical lower bound used elsewhere in this paper, shown for comparison. Bold: best "
     r"in column.}"),
    r"\label{tab:f5_gap_iaf}",
    r"{\scriptsize\setlength{\tabcolsep}{4pt}",
    r"\begin{tabular}{@{}lcccccc@{}}",
    r"\toprule",
    r" & \multicolumn{3}{c}{Family C} & \multicolumn{3}{c}{Family F} \\",
    r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}",
    r"Method & GAP$_{\mathrm{opt}}$ (\%) & Opt.\ (\%) & GAP$_{\mathrm{LB}}$ (\%) & GAP$_{\mathrm{opt}}$ (\%) & Opt.\ (\%) & GAP$_{\mathrm{LB}}$ (\%) \\",
    r"\midrule",
]
fmt = ["{:.2f}", "{:.1f}", "{:.2f}"]
for key, label in METHODS:
    cells = []
    for fam in FAMS:
        for j in range(3):
            v = stat[(fam, key)][j]
            txt = fmt[j].format(v)
            cells.append(rf"\textbf{{{txt}}}" if abs(v - best[(fam, j)]) < 1e-12 else txt)
    lines.append(f"{label} & " + " & ".join(cells) + r" \\")
lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
out = ROOT / "paper" / "f5_gap_to_iaf_reference.tex"
out.write_text("\n".join(lines), encoding="utf-8")
print(out)
print("\n".join(lines))
