"""
analysis/make_table_state_recalibration.py
============================================
Gera paper/f10_state_recalibration.tex a partir de results/state_recalibration_entrada98.csv
(+ results/results.csv para os controles). Mesmos calculos de
analysis/report_entrada98_state_recalibration.py (hash congelado; este script NAO o altera);
a coerencia com o relatorio e' verificada ao final (assert nos numeros-chave).

Uso: python -m analysis.make_table_state_recalibration
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats as sstats

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from analysis.stats import holm_bonferroni  # noqa: E402

new = pd.read_csv(ROOT / "results" / "state_recalibration_entrada98.csv")
old = pd.read_csv(ROOT / "results" / "results.csv")
both = pd.concat([new.assign(src="new"), old.assign(src="old")], ignore_index=True)
order = old.groupby("instance").n.first().sort_values().index.tolist()


def series(method, cls):
    d = both[(both.method == method) & (both.instance == cls)].sort_values("src").drop_duplicates(["instance", "rep"], keep="first")
    return d.set_index(["instance", "rep"]).gap_pct


def paired(method, control, classes=None):
    a, b = [], []
    for cls in (classes or order):
        x, y = series(method, cls), series(control, cls)
        idx = x.index.intersection(y.index)
        a.append(x.loc[idx]); b.append(y.loc[idx])
    x, y = pd.concat(a), pd.concat(b)
    cm = y.groupby(level=0).mean()
    scale = y.index.get_level_values(0).map(cm).to_numpy()
    d = (x.to_numpy() - y.to_numpy()) / np.where(scale > 0, scale, np.nan)
    ok = ~np.isnan(d) & (d != 0)
    return 100 * float((x.sum() - y.sum()) / y.sum()), float(sstats.wilcoxon(d[ok]).pvalue)


rows = []
for fw, ctrl in [("ig", "ig_random"), ("ils", "ils_random")]:
    fam = []
    for arm in ("cal", "rel"):
        m = f"{fw}_ql_{arm}"
        pct, p = paired(m, ctrl)
        fam.append((m, pct, p))
    adj = holm_bonferroni([p for _, _, p in fam], alpha=0.05)["p_adjusted"]
    for (m, pct, p), ph in zip(fam, adj):
        sub = new[new.method == m]
        f1 = sub.f1_bins.str.split("|", expand=True).astype(float).max(axis=1).mean()
        f2 = sub.f2_bins.str.split("|", expand=True).astype(float).max(axis=1).mean()
        flat = None
        rows.append(dict(m=m, fw=fw.upper(), arm=m.split("_")[-1], states=sub.distinct_states.mean(), f1=f1, f2=f2,
                         pct=pct, ph=ph, flat=flat))
ORIG6 = ["rand_20j_4m", "rand_20j_6m", "rand_30j_8m", "rand_50j_10m", "rand_75j_15m", "rand_100j_20m"]
sec = []                                  # mesma ordem do relatorio: por braco: flat, ig_ql, ils_ql(6 orig.)
for arm in ("cal", "rel"):
    sec.append(("ig", arm, "flat", paired(f"ig_ql_{arm}", "ig_ql_flat")))
    sec.append(("ig", arm, "default", paired(f"ig_ql_{arm}", "ig_ql")))
    sec.append(("ils", arm, "default", paired(f"ils_ql_{arm}", "ils_ql", ORIG6)))
adj_sec = holm_bonferroni([t[3][1] for t in sec], alpha=0.05)["p_adjusted"]
for (fw, arm, kind, (pct, p)), ph in zip(sec, adj_sec):
    if kind == "flat":
        for r in rows:
            if r["m"] == f"ig_ql_{arm}":
                r["flat"] = (pct, ph)
# coerencia com o relatorio congelado
byname = {r["m"]: r for r in rows}
assert abs(byname["ig_ql_cal"]["pct"] - (-3.137)) < 0.01 and abs(byname["ils_ql_rel"]["pct"] - 4.675) < 0.01, "diverge do relatorio"
assert abs(byname["ig_ql_cal"]["flat"][1] - 0.01214) < 0.001 and abs(byname["ig_ql_rel"]["flat"][1] - 0.004329) < 0.001, "p_holm secundario diverge"


def fp(p):
    return "$<10^{-3}$" if p < 1e-3 else f"{p:.3f}"


def sg(x, fmt):
    return format(x, fmt).replace("-", "$-$").replace("+", "$+$")


lines = [
    "% Auto-generated by analysis/make_table_state_recalibration.py (Entrada 98)",
    r"\begin{table}[t]",
    r"\centering",
    (r"\caption{Q-Learning with a recalibrated state ($N=100$ instances in each of the 12 classes). ``States'' is the mean "
     r"number of distinct states visited per run; ``Top bin'' is the mean share of the most occupied bin of $f_1$ / $f_2$ "
     r"(1.00 in the original state, whose load features stay in one bin at every step). $\Delta$ is the pooled relative change "
     r"in GAP against random selection with the same search mechanism (negative = Q-Learning better); $p_{\mathrm{holm}}$ is "
     r"Holm-adjusted over the two arms of each mechanism (paired Wilcoxon on class-standardised differences). ``cal'': "
     r"thresholds at the terciles of each feature in calibration runs; ``rel'': features relative to their value at the start of the "
     r"run, with tercile thresholds. The last column compares the IG arms with the stateless TD learner "
     r"(\texttt{ig\_ql\_flat}).}"),
    r"\label{tab:f10_state}",
    r"{\scriptsize\setlength{\tabcolsep}{4pt}",
    r"\begin{tabular}{@{}llrcccc@{}}",
    r"\toprule",
    r"Mechanism & State & States & Top bin ($f_1$ / $f_2$) & $\Delta$ vs random (\%) & $p_{\mathrm{holm}}$ & $\Delta$ vs stateless (\%) \\",
    r"\midrule",
    r"IG & original & 5--7 & 1.00 / 1.00 & see Table~\ref{tab:f3_ablation} & & \\",
]
for r in rows:
    fl = f"{sg(r['flat'][0], '+.1f')} ({fp(r['flat'][1])})" if r["flat"] else "--"
    lines.append(f"{r['fw']} & {r['arm']} & {r['states']:.1f} & {r['f1']:.2f} / {r['f2']:.2f} & "
                 f"{sg(r['pct'], '+.1f')} & {fp(r['ph'])} & {fl} \\\\")
    if r["m"] == "ig_ql_rel":
        lines.append(r"\midrule")
lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
(ROOT / "paper" / "f10_state_recalibration.tex").write_text("\n".join(lines), encoding="utf-8")
print("\n".join(lines[-12:]))
