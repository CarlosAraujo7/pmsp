"""Gera paper/f42_dqn.tex: o DQN maior (2 x 64, replay, rede-alvo) e o espaco de acao conjunto (Entradas 173-175). Fontes: results/entrada173_dqn_primary.csv, entrada173_dqn_capture.csv, entrada173_dqn_headroom.csv.
Uso: python -m analysis.make_table_dqn
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
P = pd.read_csv(R / "entrada173_dqn_primary.csv").set_index("id")
C = pd.read_csv(R / "entrada173_dqn_capture.csv")
H = pd.read_csv(R / "entrada173_dqn_headroom.csv").set_index("ambiente")
NAME = {"R": r"R$||C_{\max}$ benchmark, $d/n$ (5 actions)", "P5": r"P$||C_{\max}$, $d/n$ (5 actions)", "P15": r"P$||C_{\max}$, strategy $\times$ size (15 actions)"}


def cell(r):
    return f"{r.mean_d_pct:+.3f} [{r.ci90_lo:+.3f}, {r.ci90_hi:+.3f}]"


def ph(p):
    return f"{p:.2f}" if p >= 0.01 else f"{p:.0e}".replace("e-0", "e-").replace("e-", r"\times10^{-") + "}"


rows = []
for env in ("R", "P5", "P15"):
    a, b = P.loc[f"I1{env}"], P.loc[f"I2{env}"]
    cap = C[(C.ambiente == env) & (C.aprendiz == "dqn")].captura.iloc[0]
    orc = C[(C.ambiente == env) & (C.aprendiz == "oraculo")].ganho_sobre_aleatorio.iloc[0]
    h = H.loc[env]
    n_ = f"{int(a.n):,}".replace(",", "{,}")
    rows.append(f"{NAME[env]} & {n_} & {cell(a)} & ${ph(a.p_holm)}$ & {cell(b)} & ${ph(b.p_holm)}$ & {orc:+.3f} & {cap:+.2f} & {h.spearman_folga_ganho_dqn:+.2f} & {h.razao_cpu_dqn_aleatorio:.1f} \\\\")
L = ["% Auto-generated by analysis/make_table_dqn.py (Entrada 175)", "\\begin{table}[t]", "\\centering",
     "\\caption{A larger neural policy and a larger action space do not change the conclusion. Online DQN ($2\\times64$ units, replay, target network, success history in the context; learning rate chosen on tuning instances) against uniform random choice of the same actions (I1: negative favours the DQN) "
     "and against the configuration validated offline on separate instances (I2: negative favours validation); $\\bar d$ in \\% of the makespan with the 90\\% interval, Holm over six tests. Oracle: best fixed action per instance against random choice (headroom); capture: gain of the DQN over random choice divided by the gain of the validated choice (negative: worse than random); "
     "$\\rho$: Spearman correlation across cells between the headroom and the gain of the DQN; CPU: ratio to random choice.}",
     "\\label{tab:f42_dqn}", "{\\scriptsize\\setlength{\\tabcolsep}{2.5pt}", "\\begin{tabular}{@{}lrlrlrrrrr@{}}", "\\toprule",
     "Environment (actions) & $N$ & I1: DQN vs random & $p_{\\mathrm{H}}$ & I2: validated vs DQN & $p_{\\mathrm{H}}$ & Oracle & Capture & $\\rho$ & CPU \\\\", "\\midrule"] + rows + ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
(ROOT / "paper" / "f42_dqn.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
print("ok -> paper/f42_dqn.tex")
print("\n".join(rows))
