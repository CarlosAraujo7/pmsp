"""
analysis/make_table_granularity.py
====================================
Gera paper/f9_granularity.tex a partir de results/granularity_factorial_entrada98.csv
(item 3, Entrada 98): GAP medio de ig_ql e ils_ql por faixa H (granularidade) e n/m.
Negrito = metodo Holm-significativamente melhor na celula (Wilcoxon pareado, Holm
sobre as 15 celulas); sem negrito = empate/nao significativo.

Uso: python -m analysis.make_table_granularity
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats as sstats

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from analysis.stats import holm_bonferroni  # noqa: E402

df = pd.read_csv(ROOT / "results" / "granularity_factorial_entrada98.csv")
w = df.pivot_table(index=["m", "H", "k", "dup_ratio", "cv"], columns="method", values="gap_pct").reset_index()
cells = {}
for (m, H), g in w.groupby(["m", "H"]):
    d = (g.ig_ql - g.ils_ql).to_numpy(); nz = d[d != 0]
    p = float(sstats.wilcoxon(nz).pvalue) if len(nz) >= 8 else 1.0
    cells[(m, H)] = dict(ig=g.ig_ql.mean(), ils=g.ils_ql.mean(), p=p, dup=g.dup_ratio.mean(), cv=g.cv.mean())
keys = list(cells)
adj = holm_bonferroni([cells[k]["p"] for k in keys], alpha=0.05)
for k, pa, rj in zip(keys, adj["p_adjusted"], adj["reject"]):
    cells[k]["sig"] = bool(rj)


def cell(c):
    ig, ils = c["ig"], c["ils"]
    prec = 2 if max(ig, ils) >= 0.05 else 3
    s_ig, s_ils = f"{ig:.{prec}f}", f"{ils:.{prec}f}"
    if c["sig"]:
        if ig < ils:
            s_ig = rf"\textbf{{{s_ig}}}"
        else:
            s_ils = rf"\textbf{{{s_ils}}}"
    return f"{s_ig} / {s_ils}"


HS = sorted({h for _, h in cells})
exp = {100: "10^{2}", 1000: "10^{3}", 10000: "10^{4}", 10 ** 6: "10^{6}", 10 ** 8: "10^{8}"}
lines = [
    "% Auto-generated by analysis/make_table_granularity.py (Entrada 98)",
    r"\begin{table}[t]",
    r"\centering",
    (r"\caption{Granularity of the processing times versus $n/m$ ($n=150$, $p_j \sim U[1,H]$, 30 instances per cell, the same "
     r"instance indices in every cell). Mean GAP (\%) of \textsc{IG-QL} / \textsc{ILS-QL}; bold marks the method that is "
     r"Holm-significantly better in the cell (paired Wilcoxon, Holm over the 15 cells), no bold means a tie. ``Dup.'' is the mean "
     r"share of jobs whose processing time duplicates another's; ``CV'' is the coefficient of variation of the processing times.}"),
    r"\label{tab:f9_granularity}",
    r"{\scriptsize\setlength{\tabcolsep}{4pt}",
    r"\begin{tabular}{@{}lrrccc@{}}",
    r"\toprule",
    r"$H$ & Dup. & CV & $n/m=3$ & $n/m=10$ & $n/m=30$ \\",
    r"\midrule",
]
for H in HS:
    ref = cells[(5, H)]
    lines.append(rf"${exp[H]}$ & {ref['dup']:.3f} & {ref['cv']:.3f} & {cell(cells[(50, H)])} & {cell(cells[(15, H)])} & {cell(cells[(5, H)])} \\")
lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
(ROOT / "paper" / "f9_granularity.tex").write_text("\n".join(lines), encoding="utf-8")
print("\n".join(lines[-12:]))
