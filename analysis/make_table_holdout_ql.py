"""
analysis/make_table_holdout_ql.py
===================================
Gera paper/f6_holdout_ql_effect.tex a partir de
results/entrada90_family_level_{exploratory,holdout}.csv (familia
PRIMARIA: ig_ql vs ig_random por familia externa). Entrada 90/91.

Uso: python -m analysis.make_table_holdout_ql
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
ex = pd.read_csv(ROOT / "results" / "entrada90_family_level_exploratory.csv")
ho = pd.read_csv(ROOT / "results" / "entrada90_family_level_holdout.csv")


def prim(df):
    return df[(df.holm_family.str.startswith("P")) & (df.comparator == "ig_random")].set_index("family")


def sg(x, fmt):
    t = format(x, fmt)          # e.g. '-0.010' or '+0.018'
    return t.replace("-", "$-$").replace("+", "$+$")


def f_p(p):
    return "$<10^{-3}$" if p < 1e-3 else f"{p:.3f}"


rows = []
for label, df in [("Exploratory (6{,}780-instance sample)", prim(ex)), ("Confirmatory (4{,}160 held-out instances)", prim(ho))]:
    rows.append(rf"\multicolumn{{7}}{{@{{}}l}}{{\emph{{{label}}}}} \\")
    for fam in ["B", "C", "E"]:
        r = df.loc[fam]
        rows.append(
            f"{fam} & {int(r.n)} & {int(r.ql_better)}/{int(r.ql_worse)}/{int(r.tie)} & "
            f"{sg(r.mean_diff_pp, '+.3f')} [{sg(r.ci_low_pp, '+.3f')}, {sg(r.ci_high_pp, '+.3f')}] & "
            f"{sg(r.rel_change_pct, '+.2f')} & {sg(r.rank_biserial, '+.2f')} & {f_p(r.p_holm)} \\\\")
    rows.append(r"\midrule" if "Exploratory" in label else "")
rows = [r for r in rows if r != ""]

tex = "\n".join([
    "% Auto-generated by analysis/make_table_holdout_ql.py (Entrada 91)",
    r"\begin{table}[t]",
    r"\centering",
    (r"\caption{Family-level paired comparison of \textsc{IG-QL} against \textsc{IG-Random} on the external "
     r"families. Differences are \textsc{IG-QL} minus \textsc{IG-Random} in GAP percentage points (negative = "
     r"\textsc{IG-QL} better), with a bootstrap 95\% interval for the mean; ``Better/worse/tie'' counts "
     r"instances. The rank-biserial correlation is negative when \textsc{IG-QL} is better. $p_{\mathrm{holm}}$ "
     r"is Holm-adjusted over the three families of each block. The exploratory block generated the hypothesis; "
     r"the confirmatory block applies a rule frozen before the held-out instances were run. Family F has no "
     r"unseen instances and is therefore not testable confirmatorily.}"),
    r"\label{tab:f6_holdout_ql}",
    r"{\scriptsize\setlength{\tabcolsep}{3pt}",
    r"\begin{tabular}{@{}lrcccrr@{}}",
    r"\toprule",
    r"Family & $N$ & Better/worse/tie & $\Delta$GAP [95\% CI] (pp) & $\Delta$GAP (\%) & $r_{rb}$ & $p_{\mathrm{holm}}$ \\",
    r"\midrule",
    *rows,
    r"\bottomrule",
    r"\end{tabular}}",
    r"\end{table}",
    "",
])
out = ROOT / "paper" / "f6_holdout_ql_effect.tex"
out.write_text(tex, encoding="utf-8")
print(tex)
