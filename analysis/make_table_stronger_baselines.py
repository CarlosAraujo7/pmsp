"""
analysis/make_table_stronger_baselines.py (Entrada 102)
Gera paper/f12_stronger_baselines.tex (por classe sintetica: GAP vs LB arc-flow certificado e % de solucoes
PROVADAMENTE otimas para MultiFit, LDM, IG-QL e IG-QL partindo da melhor construtiva) e
paper/f13_stronger_baselines_tests.tex (os 8 testes pre-registrados da Entrada 102).
Fontes: results.csv, results/seeded_baselines_entrada102.csv, results/exact_reference_synthetic_entrada101.csv,
results/entrada102_seeded_primary.csv.   Uso: python -m analysis.make_table_stronger_baselines
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from analysis.report_entrada102_seeded_baselines import load_synthetic  # noqa: E402

S = load_synthetic().dropna(subset=["lpt", "multifit", "ig_ql", "ldm", "ig_ql_seed", "ig_random_seed"])
KEYS = ["multifit", "ldm", "ig_ql", "ig_ql_seed"]
LAB = {"multifit": r"\textsc{MultiFit}", "ldm": r"\textsc{LDM}", "ig_ql": r"\textsc{IG-QL}", "ig_ql_seed": r"\textsc{IG-QL}$^{+}$"}


def row(d):
    g = [100 * ((d[k] - d.lb_lp) / d.lb_lp).mean() for k in KEYS]
    o = [100 * (d[k] == d.lb_lp).mean() for k in KEYS]
    return g, o


lines = [
    "% Auto-generated by analysis/make_table_stronger_baselines.py (Entrada 102)",
    r"\begin{table}[t]",
    r"\centering",
    (r"\caption{Stronger baselines against the certified arc-flow lower bound (LB$^{\mathrm{AF}}$): mean GAP (\%) and share of "
     r"instances solved \emph{provably} to optimality (makespan $=$ LB$^{\mathrm{AF}}$). \textsc{IG-QL}$^{+}$ is \textsc{IG-QL} started "
     r"from the best of LPT, \textsc{MultiFit} and \textsc{LDM}. Classes sorted by $n$; $N=100$ per class ($30$ for $(20,4)$). "
     r"Bold: lowest GAP in the row (ties all bold).}"),
    r"\label{tab:f12_stronger}",
    r"{\scriptsize\setlength{\tabcolsep}{3.5pt}",
    r"\begin{tabular}{@{}rr rrrr rrrr@{}}",
    r"\toprule",
    r" & & \multicolumn{4}{c}{GAP vs LB$^{\mathrm{AF}}$ (\%)} & \multicolumn{4}{c}{Provably optimal (\%)} \\",
    r"\cmidrule(lr){3-6}\cmidrule(lr){7-10}",
    r"$n$ & $m$ & " + " & ".join(LAB[k] for k in KEYS) + " & " + " & ".join(LAB[k] for k in KEYS) + r" \\",
    r"\midrule",
]
order = S.groupby("group").n.first().sort_values(kind="stable").index
for grp in order:
    d = S[S.group == grp]
    g, o = row(d)
    lo = min(round(x, 3) for x in g)
    gs = [(r"\textbf{%.3f}" if round(x, 3) == lo else "%.3f") % x for x in g]
    lines.append(f"{int(d.n.iloc[0])} & {int(d.m.iloc[0])} & " + " & ".join(gs) + " & " + " & ".join(f"{x:.0f}" for x in o) + r" \\")
g, o = row(S)
lo = min(round(x, 3) for x in g)
gs = [(r"\textbf{%.3f}" if round(x, 3) == lo else "%.3f") % x for x in g]
lines += [r"\midrule", rf"\multicolumn{{2}}{{c}}{{All ({len(S):,})}} & ".replace(",", r"{,}") + " & ".join(gs) + " & " + " & ".join(f"{x:.1f}" for x in o) + r" \\",
          r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
(ROOT / "paper" / "f12_stronger_baselines.tex").write_text("\n".join(lines), encoding="utf-8")
print("\n".join(lines[9:]))

# ---- testes pre-registrados
P = pd.read_csv(ROOT / "results" / "entrada102_seeded_primary.csv")
name = {"P1": r"\textsc{IG-QL}$^{+}$ vs.\ \textsc{IG-Random}$^{+}$", "P2": r"\textsc{IG-QL}$^{+}$ vs.\ \textsc{IG-QL}",
        "P3": r"\textsc{IG-QL}$^{+}$ vs.\ best constructive", "P4": r"\textsc{IG-QL} vs.\ \textsc{LDM}"}
t = [
    "% Auto-generated by analysis/make_table_stronger_baselines.py (Entrada 102)",
    r"\begin{table}[t]",
    r"\centering",
    (r"\caption{Pre-specified paired tests with stronger baselines (Wilcoxon signed-rank, two-sided; Holm over all eight tests). "
     r"$\bar d$: mean relative makespan difference $100(C_A-C_B)/C_B$ in \% (negative: first method better); "
     r"W/L/T: instances where the first method is better/worse/tied; $r$: rank-biserial correlation (negative: first better). "
     r"All eight hypotheses are confirmed, but P1 is practically negligible ($|\bar d|<0.05\%$).}"),
    r"\label{tab:f13_tests}",
    r"{\scriptsize\setlength{\tabcolsep}{3.5pt}",
    r"\begin{tabular}{@{}llrrrrrr@{}}",
    r"\toprule",
    r"Set & Comparison & $N$ & W/L/T & $\bar d$ (\%) & $r$ & $p_{\mathrm{Holm}}$ & Neglig. \\",
    r"\midrule",
]
for st, lbl in [("S", "Synthetic"), ("X", "External")]:
    for r in P[P.set == st].itertuples():
        ph = "$<10^{-300}$" if r.p_holm < 1e-300 else (f"{r.p_holm:.3f}" if r.p_holm >= 0.001 else r"$%s$" % (f"{r.p_holm:.0e}".replace("e-0", r"\times10^{-").replace("e-", r"\times10^{-") + "}"))
        t.append(f"{lbl if r.id == 'P1' else ''} & {r.id}: {name[r.id]} & {r.n:,} & {r.better}/{r.worse}/{r.tie} & {r.mean_d_pct:.3f} & {r.rank_biserial:.2f} & {ph} & {'yes' if r.equivalent else 'no'} \\\\".replace(",", r"{,}", 1))
    if st == "S":
        t.append(r"\midrule")
t += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
(ROOT / "paper" / "f13_stronger_baselines_tests.tex").write_text("\n".join(t), encoding="utf-8")
print("\n".join(t[9:]))
