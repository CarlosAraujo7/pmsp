"""Gera paper/f41_bigtrain.tex (mais dados de treino offline: 280 -> 700; Entrada 168/169) a partir de results/entrada168_bigtrain_primary.csv e entrada168_bigtrain.txt.
Uso: python -m analysis.make_table_bigtrain
"""
from __future__ import annotations

import re
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
P = pd.read_csv(R / "entrada168_bigtrain_primary.csv").set_index("id")
txt = (R / "entrada168_bigtrain.txt").read_text(encoding="utf-8")
curve = {m.group(1): (float(m.group(2)), float(m.group(3)), float(m.group(4)), int(m.group(5)), int(m.group(6)), int(m.group(7)))
         for m in re.finditer(r"  (kNN 280|kNN 700|MLP 280|MLP 700): d = ([+-]\d+\.\d+)% \[IC90 ([+-]\d+\.\d+), ([+-]\d+\.\d+)\] \((\d+)/(\d+)/(\d+)\)", txt)}


def fmt_p(p):
    if p >= 0.01:
        return f"{p:.2f}"
    e = int(np.floor(np.log10(p)))
    return f"${p / 10 ** e:.0f}\\times10^{{{e}}}$"


names = {"H1": "kNN selector ($700$) vs validated per cell ($700$)", "H2": "MLP selector ($700$) vs validated per cell ($700$)", "H3": "validated per cell: $700$ vs $280$ training instances", "H4": "validated per cell ($700$) vs random $d$"}
L = ["% Auto-generated by analysis/make_table_bigtrain.py (Entrada 168/169)", "\\begin{table}[t]", "\\centering",
     "\\caption{More offline training data for the instance-conditional selectors (unrelated machines, destruction size; the $280$ tuning instances plus the $420$ reserved ones, $700$ in all, disjoint from the $700$ test instances; design and predictions recorded beforehand). "
     "$\\bar d$ in \\% of the makespan (negative: first better); Wilcoxon, Holm over four; confirmed: $p_{\\mathrm{Holm}}<0.05$ and $\\bar d<0$. \\emph{Caution on H2:} the signed-rank test flags the MLP as confirmed, but it is worse in $160$ instances and better in only $36$ (rank-biserial $+0.76$); the mean is "
     "$-0.011\\%$ with an interval that includes zero (equivalent within $\\pm0.05\\%$). The honest reading is parity, not superiority. Lower block (descriptive): the same selectors against validation per cell with the same training set.}",
     "\\label{tab:f41_bigtrain}", "{\\scriptsize\\setlength{\\tabcolsep}{3pt}", "\\begin{tabular}{@{}lrrrrl@{}}", "\\toprule", "Comparison & W/L/T & $\\bar d$ (\\%) & 90\\% interval & $p_{\\mathrm{Holm}}$ & Confirmed \\\\", "\\midrule"]
for k in ("H1", "H2", "H3", "H4"):
    r = P.loc[k]
    L.append(f"{names[k]} & {int(r.better)}/{int(r.worse)}/{int(r.tie)} & {r.mean_d_pct:+.3f} & [{r.ci90_lo:+.3f}, {r.ci90_hi:+.3f}] & {fmt_p(r.p_holm)} & {'yes' if r.confirmada else 'no'} \\\\")
L.append("\\midrule")
for lab, key in [("kNN, $280$ training instances", "kNN 280"), ("kNN, $700$ training instances", "kNN 700"), ("MLP, $280$ training instances", "MLP 280"), ("MLP, $700$ training instances", "MLP 700")]:
    d, lo, hi, b, w, t = curve[key]
    L.append(f"\\quad {lab} vs validated per cell & {b}/{w}/{t} & {d:+.3f} & [{lo:+.3f}, {hi:+.3f}] & -- & -- \\\\")
L += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
(ROOT / "paper" / "f41_bigtrain.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
print("ok -> paper/f41_bigtrain.tex", curve)
