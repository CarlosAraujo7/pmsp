"""Tabela da ablacao do IG do artigo do CEC (cec/tab_ablation.tex), gerada de results/entrada284_contrasts.csv e entrada284_ablation.txt (Entrada 284: descida curta) e de entrada285_contrasts.csv e entrada285_fulldescent.txt (Entrada 285: descida completa).
Uso: python -m analysis.make_table_cec_ablation"""
from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
C4 = pd.read_csv(R / "entrada284_contrasts.csv", index_col=0)
C5 = pd.read_csv(R / "entrada285_contrasts.csv", index_col=0)
C5b = pd.read_csv(R / "entrada285b_contrasts.csv", index_col=0)
t4 = (R / "entrada284_ablation.txt").read_text(encoding="utf-8")
t5 = (R / "entrada285_fulldescent.txt").read_text(encoding="utf-8")
t5b = (R / "entrada285b_fixedsize.txt").read_text(encoding="utf-8")
gap = dict(re.findall(r"(G0|R0|G1|R1) ([\d.]+)", re.search(r"lacuna, %\), media sobre as 12 classes: (.*)", t4).group(1)))
gap.update(dict(re.findall(r"(G2|R2) ([\d.]+)", re.search(r"lacuna media ao limite inferior \(%\), media sobre as classes: (.*)", t5).group(1))))
gap["R2*"] = re.search(r"lacuna media do R2\*: ([\d.]+)%", t5b).group(1)
gap = {k: f"{float(v):.2f}" for k, v in gap.items()}
BS = chr(92)
# (rotulo, contraste a iteracoes iguais, contraste a CPU igual ou None)
ROWS = [("G0 vs R0: greedy vs random reinsertion", ("4", "C1"), ("4", "C1c")),
        ("G1 vs R1: the same, short descent", ("4", "C2"), ("4", "C2c")),
        ("G2 vs R2: the same, full descent", ("5", "F3"), ("5", "F3c")),
        ("R2 vs R1: full vs short descent, random", ("5", "F1"), None),
        ("G0 vs R2: plain IG vs classical ILS", ("5", "F4"), ("5", "F4c")),
        ("G0 vs R2*: the same, best kick size", ("5b", "S1"), ("5b", "S2"))]


def cell(src):
    if src is None:
        return "-- & --"
    df = {"4": C4, "5": C5, "5b": C5b}[src[0]]
    r = df.loc[src[1]]
    return f"{r.ganho_medio:+.2f} & {int(r.vence_alem)}"


lines = [
    "% Auto-generated by analysis/make_table_cec_ablation.py (results/entrada284_contrasts.csv, entrada285_contrasts.csv)",
    BS + "begin{table}[t]",
    BS + "caption{Components of the IG, with the action drawn at random among five destruction sizes (no learner; P$||" + BS + "Cmax$, $12$ classes $\\times$ $100$ instances, five seeds). G: greedy reconstruction; R: the removed jobs reinserted on random machines; "
    "$0$, $1$, $2$: no descent, the IG's short descent (at most two improving moves), a descent to a local optimum; R2 is the classical ILS and R2* the same with the best fixed kick size of each class, chosen on the test instances. "
    "Gain of the first-named variant in points of the makespan (mean over classes) and number of classes (of $12$) in which it wins beyond the margin. Mean gap to the bound: "
    f"G0 ${gap['G0']}\\%$, R0 ${gap['R0']}\\%$, G1 ${gap['G1']}\\%$, R1 ${gap['R1']}\\%$, G2 ${gap['G2']}\\%$, R2 ${gap['R2']}\\%$, R2* ${gap['R2*']}\\%$.}}",
    BS + "label{tab:ablation}",
    BS + "centering",
    "{" + BS + "scriptsize" + BS + "setlength{" + BS + "tabcolsep}{2.6pt}",
    BS + "begin{tabular}{@{}lrrrr@{}}",
    BS + "toprule",
    " & " + BS + "multicolumn{2}{c}{Equal iterations} & " + BS + "multicolumn{2}{c}{Equal CPU time} " + BS + BS + BS + "cmidrule(lr){2-3}" + BS + "cmidrule(l){4-5}",
    " & gain & classes & gain & classes " + BS + BS,
    BS + "midrule",
]
for lab, a, b in ROWS:
    lines.append(lab + " & " + cell(a) + " & " + cell(b) + " " + BS + BS)
lines += [BS + "bottomrule", BS + "end{tabular}}", BS + "end{table}"]
(ROOT / "cec" / "tab_ablation.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("ok -> cec/tab_ablation.tex", gap)
