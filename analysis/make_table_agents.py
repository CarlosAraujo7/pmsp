"""Gera paper/f43_agents.tex: agentes compilados em espacos de 3, 5, 15 e 30 acoes (Entradas 180-181). Fontes: results/entrada180_agents_{aiter,acpu,b,k}.csv e entrada180_agents.txt.
Uso: python -m analysis.make_table_agents
"""
from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
Ai = pd.read_csv(R / "entrada180_agents_aiter.csv").set_index("id")
Ac = pd.read_csv(R / "entrada180_agents_acpu.csv").set_index("id")
B = pd.read_csv(R / "entrada180_agents_b.csv").set_index("id")
K = pd.read_csv(R / "entrada180_agents_k.csv")
txt = (R / "entrada180_agents.txt").read_text(encoding="utf-8")
hd = {sp: -float(v) for sp, v in re.findall(r"^\s*(S\d+)\s+(-?\d\.\d+)\s*$", txt.split("folga: oraculo")[1].split("S30: fracao")[0], flags=re.M)}
NAME = {"S3": "3 strategies", "S5": "5 sizes", "S15": "15 (strategy $\\times$ size)", "S30": "30 (+ local search)"}
LN = {"ql": "Q-Learning", "ucb": "UCB1", "pg": "Policy gradient"}


def cell(r):
    return f"{r.mean_d_pct:+.3f} [{r.ci90_lo:+.3f}, {r.ci90_hi:+.3f}]"


rows = []
for sp in ("S3", "S5", "S15", "S30"):
    for k in ("ql", "ucb", "pg"):
        kr = K[(K.space == sp) & (K.learner == k)].iloc[0]
        first = f"\\multirow{{3}}{{*}}{{{NAME[sp]}}}" if k == "ql" else ""
        head = f"\\multirow{{3}}{{*}}{{${hd[sp]:.3f}$}}" if k == "ql" else ""
        rows.append(f"{first} & {head} & {LN[k]} & {kr.K_cpu:.2f} & {cell(Ai.loc[f'Aiter-{sp}-{k}'])} & {cell(Ac.loc[f'Acpu-{sp}-{k}'])} & {cell(B.loc[f'B-{sp}-{k}'])} \\\\")
    rows[-1] += " \\midrule" if sp != "S30" else ""
L = ["% Auto-generated by analysis/make_table_agents.py (Entrada 181)", "\\begin{table}[t]", "\\centering",
     "\\caption{Compiled agents in action spaces of $3$ to $30$ actions (identical machines, $12$ classes $\\times$ $100$ instances, $5$ seeds per instance, the unit of analysis is the mean of the five; $1{,}200$ pairs per row). "
     "Oracle: gain of the best fixed action per instance over random choice (\\%). $K$: CPU time of the learner over that of random choice. Equal iterations: learner vs random choice ($T=1000$). Equal CPU: learner vs random choice with $T=\\mathrm{round}(1000K)$ iterations. "
     "Validated: the best fixed action per class (chosen on $30$ separate instances per class) vs the learner, $T=1000$ (negative: the validated choice wins). $\\bar d$ in \\% of the makespan with the 90\\% interval; Holm over $12$ tests in each of the three comparisons.}",
     "\\label{tab:f43_agents}", "{\\scriptsize\\setlength{\\tabcolsep}{2.5pt}", "\\begin{tabular}{@{}llllllll@{}}", "\\toprule",
     "Actions & Oracle & Learner & $K$ & Equal iterations & Equal CPU & Validated vs learner \\\\", "\\midrule"] + rows + ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
text = "\n".join(L).replace("\\begin{tabular}{@{}llllllll@{}}", "\\begin{tabular}{@{}lllrlll@{}}")
(ROOT / "paper" / "f43_agents.tex").write_text(text + "\n", encoding="utf-8")
print("ok -> paper/f43_agents.tex")
print("\n".join(rows))
