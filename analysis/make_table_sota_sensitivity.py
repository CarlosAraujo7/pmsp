"""
analysis/make_table_sota_sensitivity.py
=========================================
Gera paper/f7_sota_sensitivity.tex: gap medio por classe de ig_ql, MULTIFIT,
SA (original e sem regra de parada) e BCO (regra do projeto, tempo igual,
I=100 publicado). Todas as medias sao calculadas nas MESMAS replicas (as
rodadas na analise de sensibilidade: N=100 para n<=100, N=30 para n>=150
e para (20,4)). Entrada 92. Fonte: results/results.csv +
results/sota_sensitivity_entrada90.csv.

Uso: python -m analysis.make_table_sota_sensitivity
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
main = pd.read_csv(ROOT / "results" / "results.csv")
sens = pd.read_csv(ROOT / "results" / "sota_sensitivity_entrada90.csv")

COLS = [("ig_ql", r"\textsc{IG-QL}"), ("multifit", r"\textsc{MultiFit}"), ("sa_li_perkins", "SA"),
        ("sa_noearly", r"SA$^{\dagger}$"), ("bco", "BCO"), ("bco_tm", r"BCO$^{\ddagger}$"),
        ("bco_I100", r"BCO$^{\S}$")]
rows = []
for (n, m), g in sens.groupby(["n", "m"]):
    reps = set(g.rep)
    inst = f"rand_{n}j_{m}m"
    vals = {}
    for key, _ in COLS:
        src = sens if key in ("sa_noearly", "bco_tm", "bco_I100") else main
        s = src[(src.instance == inst) & (src.method == key) & (src.rep.isin(reps))]
        vals[key] = s.gap_pct.mean()
    rows.append((n, m, len(reps), vals))
rows.sort()

lines = [
    "% Auto-generated by analysis/make_table_sota_sensitivity.py (Entrada 92)",
    r"\begin{table}[t]",
    r"\centering",
    (r"\caption{Mean GAP (\%) of \textsc{IG-QL} and of the published baselines under alternative budget "
     r"settings, on the same replications ($N=100$ for $n \le 100$; $N=30$ for $n \ge 150$ and for $(20,4)$). "
     r"SA and BCO are the versions used in Table~\ref{tab:f2_sota} (BCO with $I=\max(1,\lfloor T/(5n)\rfloor)$ "
     r"outer iterations). $^{\dagger}$SA without its early-stopping rule (all $T=1{,}000$ iterations). "
     r"$^{\ddagger}$BCO with $I$ calibrated so that its CPU time equals that of \textsc{IG-QL} "
     r"($I$ from 31 at $n=20$ to 6 at $n=300$). $^{\S}$BCO with the published $I=100$ (3.3--14.8$\times$ the CPU "
     r"time of \textsc{IG-QL}). Bold: best in row. \textsc{IG-QL} is Holm-significantly better than each of the three variants "
     r"$^{\dagger}$, $^{\ddagger}$ and $^{\S}$ in all 12 classes (36 of 36 tests).}"),
    r"\label{tab:f7_sota_sensitivity}",
    r"{\scriptsize\setlength{\tabcolsep}{3pt}",
    r"\begin{tabular}{@{}rrrrrrrrr@{}}",
    r"\toprule",
    r"$n$ & $m$ & " + " & ".join(lab for _, lab in COLS) + r" \\",
    r"\midrule",
]
for n, m, _, vals in rows:
    best = min(vals.values())
    cells = []
    for key, _ in COLS:
        t = f"{vals[key]:.2f}"
        cells.append(rf"\textbf{{{t}}}" if abs(vals[key] - best) < 1e-12 else t)
    lines.append(f"{n} & {m} & " + " & ".join(cells) + r" \\")
lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
out = ROOT / "paper" / "f7_sota_sensitivity.tex"
out.write_text("\n".join(lines), encoding="utf-8")
print("\n".join(lines))
