"""Gera paper/s_litaudit.tex (secao do suplemento com a auditoria de literatura da Entrada 159) a partir de results/litaudit_entrada159.csv.
Uso: python -m analysis.make_table_litaudit
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
d = pd.read_csv(ROOT / "results" / "litaudit_entrada159.csv", dtype=str, keep_default_na=False)
inc = d[d.included == "Y"].copy()
n = len(inc)
nt = int((inc.stat_test == "Y").sum())
cnt = lambda col, v: int((inc[col] == v).sum())

rows = []
for r in inc.itertuples():
    rows.append(f"arXiv:{r.id} & {r.year} & {r.random_control} & {r.budget_basis} & {r.learner_overhead_reported} & {r.offline_tuned_static} & {r.tune_test_split} & {r.stat_test} & {r.multiplicity} & {r.ablation_policy} & {r.code_or_data} & {r.claim_policy_helps} \\\\")

L = []
L.append("% Auto-generated by analysis/make_table_litaudit.py (Entrada 159)")
L.append("\\section{Audit of the literature: how often are the controls of the protocol used?}")
L.append("\\label{sec:m-litaudit}")
L.append("")
L.append(f"To check whether the controls of the protocol are common practice, {n} papers that propose a learned selector or controller of operators, strategies or parameters inside a metaheuristic for a combinatorial problem were coded. "
         "The papers were found by eight fixed queries (plus four added before reading any paper) on arXiv, 2015--2026, open full text; the protocol and the codebook were frozen before any paper was read "
         "(\\texttt{analysis/litaudit\\_codebook\\_entrada159.md}), and every exclusion is listed in \\texttt{results/litaudit\\_entrada159.csv}. "
         "Coding is conservative: ``U'' (cannot be determined from the text) counts as not demonstrated. The sample is small, restricted to open-access arXiv papers, coded by one coder (an AI assistant, reading the HTML full text with quotation of the supporting sentences), "
         "and a random sample of eight papers is listed for double coding by the author (Table~\\ref{tab:litaudit}; \\texttt{results/entrada159\\_litaudit.txt}).")
L.append("")
L.append("\\begin{table}[t]")
L.append("\\centering")
L.append("\\caption{Coding of " + str(n) + " papers with a learned selector inside a metaheuristic. RC: random-selection control of the same actions; Bud: budget basis of the comparison with variants without learning (CPU: equal time limit; ITER: equal iterations or evaluations; MIXED; U: not stated); "
         "Ovh: cost of the learner reported or discussed; Off: static competitor tuned offline; Spl: tuning/training instances separate from test instances; Stat: statistical test; Mult: correction for multiple comparisons (NA: no test); "
         "Abl: ablation that isolates the policy from the host mechanism; Code: code or data available; Claim: the paper concludes that the learned component helps (Y, MIXED). Y: yes; N: no; U: not determinable from the text.}")
L.append("\\label{tab:litaudit}")
L.append("{\\scriptsize\\setlength{\\tabcolsep}{3pt}")
L.append("\\begin{tabular}{@{}llcccccccccc@{}}")
L.append("\\toprule")
L.append("Paper & Year & RC & Bud & Ovh & Off & Spl & Stat & Mult & Abl & Code & Claim \\\\")
L.append("\\midrule")
# the table has 12 columns of data after the first two; the generator writes exactly 12 cells per row
L += [r.replace("& U &", "& U &") for r in rows]
L.append("\\midrule")
L.append(f"Y (of {n}) & & {cnt('random_control','Y')} & {cnt('budget_basis','CPU')} & {cnt('learner_overhead_reported','Y')} & {cnt('offline_tuned_static','Y')} & {cnt('tune_test_split','Y')} & {nt} & {cnt('multiplicity','Y')}/{nt} & {cnt('ablation_policy','Y')} & {cnt('code_or_data','Y')} & {cnt('claim_policy_helps','Y') + cnt('claim_policy_helps','MIXED')} \\\\")
L.append("\\bottomrule")
L.append("\\end{tabular}}")
L.append("\\end{table}")
L.append("")
L.append(f"The cheap controls are fairly common: a random-selection control in {cnt('random_control','Y')} of {n} papers and an ablation that isolates the policy in {cnt('ablation_policy','Y')}. "
         f"The controls that make a comparison budget-fair are rare: only {cnt('budget_basis','CPU')} of {n} compare with the variants without learning at an equal time limit ({cnt('budget_basis','ITER')} at equal iterations or evaluations, {cnt('budget_basis','MIXED')} mixed, {cnt('budget_basis','U')} not stated), "
         f"{cnt('offline_tuned_static','Y')} include a static configuration tuned offline as a competitor, {cnt('tune_test_split','Y')} state that tuning or training instances are separate from the test instances, and {cnt('multiplicity','Y')} of the {nt} that use a statistical test correct for multiple comparisons. "
         "All papers conclude that the learned component helps (two with mixed evidence); none reports a null result for the policy. The predictions recorded before reading were wrong for random controls, ablations, overhead reports, statistical tests and multiplicity "
         "(these were more common than predicted: five of seven predictions failed) and right for equal-CPU comparisons and offline-tuned competitors (both rare). "
         "The audit therefore supports the rows of Table~\\ref{tab:fair_vs_naive} that rest on equal iterations and on the absence of an offline-tuned competitor, and not a claim that random controls are uncommon.")
(ROOT / "paper" / "s_litaudit.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
print("ok -> paper/s_litaudit.tex")
