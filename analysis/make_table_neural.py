"""Gera paper/f39_neural.tex (tabela principal: aprendizes neurais no espaco 'tamanho de destruicao', Entrada 162/166)
a partir de results/entrada162_neural_primary.csv e results/entrada162_neural.txt.
Uso: python -m analysis.make_table_neural
"""
from __future__ import annotations

import re
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
P = pd.read_csv(R / "entrada162_neural_primary.csv")
txt = (R / "entrada162_neural.txt").read_text(encoding="utf-8")
cap = {k: float(v) for k, v in re.findall(r"(val_mlp|nq_d|ql_d|ucb_d|ql_d_pre|oracle) (-?\d+\.\d+)", txt.split("Razao de captura")[1].split("\n")[0])}


def fmt_p(p):
    if p >= 0.01:
        return f"{p:.2f}"
    e = int(np.floor(np.log10(p)))
    return f"${p / 10 ** e:.0f}\\times10^{{{e}}}$"


names = {"N1": "N1: neural Q-learning vs random $d$", "N2": "N2: validated per cell vs neural Q-learning", "N3": "N3: offline MLP selector vs validated per cell", "N4": "N4: offline MLP selector vs random $d$"}
L = ["% Auto-generated by analysis/make_table_neural.py (Entrada 162/166)", "\\begin{table}[t]", "\\centering",
     "\\caption{Neural learners for the destruction size (same $700$ test instances and actions as Tables~\\ref{tab:f33_dpolicy} and~\\ref{tab:f37_ctx}; design and predictions recorded beforehand). Neural Q-learning: a one-hidden-layer network ($16$ units) "
     "trained online by temporal differences on the context of Table~\\ref{tab:f37_ctx} (learning rate chosen on $280$ tuning instances). Offline MLP selector: a two-layer perceptron ($16\\times16$) trained on the same $280$ tuning instances to predict the ratio to the best known solution "
     "of each size from eight features of the time matrix (targets standardised per size). $\\bar d$ in \\% of the makespan (negative: first better); Wilcoxon, Holm over four; confirmed: $p_{\\mathrm{Holm}}<0.05$ and $\\bar d<0$. Last row: gain over random $d$ as a fraction of the gain of the validated choice.}",
     "\\label{tab:f39_neural}", "{\\scriptsize\\setlength{\\tabcolsep}{3pt}", "\\begin{tabular}{@{}lrrrrl@{}}", "\\toprule",
     "Comparison & W/L/T & $\\bar d$ (\\%) & 90\\% interval & $p_{\\mathrm{Holm}}$ & Confirmed \\\\", "\\midrule"]
for r in P.itertuples():
    L.append(f"{names[r.id]} & {r.better}/{r.worse}/{r.tie} & {r.mean_d_pct:+.3f} & [{r.ci90_lo:+.3f}, {r.ci90_hi:+.3f}] & {fmt_p(r.p_holm)} & {'yes' if r.confirmada else 'no'} \\\\")
L += ["\\midrule", f"\\multicolumn{{6}}{{p{{0.95\\textwidth}}}}{{Capture of the validated gain: offline MLP selector {cap['val_mlp']:.2f}; neural Q-learning {cap['nq_d']:.2f}; tabular Q-learning {cap['ql_d']:.2f}; UCB1 {cap['ucb_d']:.2f}; pre-trained Q-learning {cap['ql_d_pre']:.2f}}} \\\\",
      "\\bottomrule", "\\end{tabular}}", "\\end{table}"]
(ROOT / "paper" / "f39_neural.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
print("ok -> paper/f39_neural.tex", cap)
