"""
analysis/make_table_policy_robustness.py (Entrada 112)
Gera paper/f14_policy_robustness.tex: efeito da POLITICA Q-Learning sobre a selecao aleatoria sob variacoes de estado,
recompensa, pre-treino, hiperparametros e media por seed (Entradas 98, 104, 105, 109). d = diferenca relativa media de
makespan (%) contra o controle aleatorio pareado (negativo: Q-Learning melhor), IC90 percentil por bootstrap.
Uso: python -m analysis.make_table_policy_robustness
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from analysis.report_entrada104_signal_headroom import test  # noqa: E402

res = pd.read_csv(ROOT / "results" / "results.csv")
rec = pd.read_csv(ROOT / "results" / "state_recalibration_entrada98.csv")
sig = pd.read_csv(ROOT / "results" / "signal_headroom_entrada104.csv")
hyp = pd.read_csv(ROOT / "results" / "hyperparam_sensitivity_entrada105.csv")
sv = pd.read_csv(ROOT / "results" / "seed_variance_entrada109.csv")
cols = ["instance", "rep", "method", "makespan"]
d = pd.concat([res[res.method.isin(["ig_random", "ig_ql"])][cols], rec[rec.method == "ig_ql_cal"][cols], sig[cols]]).drop_duplicates(["instance", "rep", "method"])
w = d.pivot(index=["instance", "rep"], columns="method", values="makespan").reset_index()
w1200 = w.dropna(subset=["ig_random", "ig_ql_cal", "ig_fix0", "ig_ql_dense_cal"]).copy()
rows = []


def add(label, n, t, note=""):
    rows.append((label, n, t["mean_d_pct"], t["ci90_lo"], t["ci90_hi"], note))


# referencias
wk = w.dropna(subset=["ig_ql"])
add(r"Original \texttt{ig\_ql} (sparse reward, default state)", len(wk), test(wk.ig_ql, wk.ig_random))
add(r"Informative state (\texttt{cal})", len(w1200), test(w1200.ig_ql_cal, w1200.ig_random))
add(r"Dense reward (load balance)", len(w1200), test(w1200.ig_ql_dense_cal, w1200.ig_random))
add(r"Pre-trained per class", len(w1200), test(w1200.ig_ql_ws_cal, w1200.ig_random))
add(r"Dense reward + pre-training", len(w1200), test(w1200.ig_ql_dense_ws_cal, w1200.ig_random))
# folga: melhor estratégia fixa por classe e oráculo por instância
fix = ["ig_fix0", "ig_fix1", "ig_fix2"]
best = []
for cls, g in w1200.groupby("instance"):
    k = min(fix, key=lambda c: g[c].mean())
    best.append(g[k])
bestser = pd.concat(best).reindex(w1200.index)
add(r"Best fixed strategy per class (in-sample)", len(w1200), test(bestser, w1200.ig_random))
add(r"Per-instance oracle of the 3 strategies", len(w1200), test(w1200[fix].min(axis=1), w1200.ig_random))
# hiperparametros: pares de results.csv (padrao) e do proprio hyperparam
hb = pd.concat([res[res.method.isin(["ig_random", "ig_ql"]) & (res.rep < 50)][cols], hyp[cols]]).drop_duplicates(["instance", "rep", "method"])
hw = hb.pivot(index=["instance", "rep"], columns="method", values="makespan").reset_index().dropna()
hw = hw[hw.instance.isin(hyp.instance.unique())]
for lab, a, b in [(r"Destruction size $d=0.1n$", "ig_ql_d10", "ig_random_d10"), (r"Destruction size $d=0.2n$", "ig_ql_d20", "ig_random_d20"),
                  (r"Destruction size $d=0.4n$", "ig_ql_d40", "ig_random_d40")]:
    add(lab, len(hw), test(hw[a], hw[b]))
rng = [test(hw[k], hw.ig_random) for k in ["ig_ql_a05", "ig_ql_a30", "ig_ql_g50", "ig_ql_g99", "ig_ql_e990", "ig_ql_e999"]]
lo = min(r["mean_d_pct"] for r in rng)
hi = max(r["mean_d_pct"] for r in rng)
rows.append((r"$\alpha$, $\gamma$, $\varepsilon$-decay (6 settings; range)", len(hw), None, lo, hi, "range"))
# medias por seed
m = sv.groupby(["instance", "method", "rep"]).makespan.mean().unstack("method").reset_index()
add(r"Seed-averaged (10 seeds; 3 classes)", len(m), test(m.ig_ql, m.ig_random))

L = ["% Auto-generated by analysis/make_table_policy_robustness.py (Entrada 112)", r"\begin{table}[t]", r"\centering",
     (r"\caption{Effect of the Q-Learning policy over random destruction, under variations of the state, reward, training, "
      r"hyperparameters and seed averaging. $\bar d$: mean relative makespan difference (\%; negative: Q-Learning better) against the "
      r"paired random control; 90\% percentile-bootstrap interval. Positive values mean that Q-Learning is \emph{worse} than random. "
      r"The two rows of the middle block are not learners: they bound the headroom, i.e.\ what any selector among the three destruction "
      r"strategies could gain (best fixed strategy per class, chosen in-sample; omniscient per-instance choice).}"),
     r"\label{tab:f14_policy}", r"{\scriptsize\setlength{\tabcolsep}{4pt}", r"\begin{tabular}{@{}lrrr@{}}", r"\toprule",
     r"Variant & $N$ & $\bar d$ (\%) & 90\% interval \\", r"\midrule"]
for lab, n, dm, lo_, hi_, note in rows:
    if note == "range":
        L.append(f"{lab} & {n} & --- & [{lo_:+.3f}, {hi_:+.3f}] \\\\")
    else:
        L.append(f"{lab} & {n:,} & {dm:+.3f} & [{lo_:+.3f}, {hi_:+.3f}] \\\\".replace(f"{n:,}", f"{n:,}".replace(",", "{,}")))
    if lab.startswith("Dense reward +") or lab.startswith("Per-instance oracle"):
        L.append(r"\midrule")
L += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
(ROOT / "paper" / "f14_policy_robustness.tex").write_text("\n".join(L), encoding="utf-8")
print("\n".join(L[8:]))
