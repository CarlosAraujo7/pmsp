    sys.path.insert(0, str(ROOT))
    from analysis.report_entrada180_agents import rel

    def g(W, k):
        return float(-rel(W[k], W["rand"]).mean())

    LA = ["% Auto-generated by analysis/make_table_journal.py", "\\begin{table}[t]",
          "\\caption{Order sensitivity of the standard Q-Learning on the standard benchmark ($140$ test instances, one per cell of type, $m$ and $n$; two seeds; gains over random choice in points, positive = better). ql: standard; ql\\_v0: the same learner with the class's validated action moved to index $0$; val: the validated action. Index-0 share: fraction of the learner's choices that fall on the action listed first (random choice: $1/A$); ql\\_v0 share: fraction on the validated action.}",
          "\\label{tab:order_a}", "\\centering", "{\\scriptsize\\setlength{\\tabcolsep}{5pt}", "\\begin{tabular}{@{}lrrrrrr@{}}", "\\toprule",
          "Space & $1/A$ & ql index-0 share & ql & ql\\_v0 & val & ql\\_v0 share of val \\\\", "\\midrule"]
    for sp, A in (("B5", 5), ("B15", 15), ("B30", 30)):
        D1 = pd.read_csv(R / f"mech_{sp}_entrada258.csv")
        D2 = pd.read_csv(R / f"mech2_{sp}_entrada258.csv")
