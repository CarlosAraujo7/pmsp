# ---------------------------------------------------------------- standard benchmark of Fanjul-Peyro and Ruiz (Entrada 256)
if (R / "entrada256_fanjul_cells.csv").exists():
    F = pd.read_csv(R / "entrada256_fanjul_cells.csv")
    TF = pd.read_csv(R / "entrada256_fanjul_tests.csv").set_index("id")
    LRN = ["ql", "ucb", "pg", "alns", "qo", "iq", "fr"]
    NAMES = {"JobsCorre": "correlated jobs", "MaqCorre": "correlated machines", "U1a100": "$U[1,100]$", "U10a100": "$U[10,100]$", "U100a120": "$U[100,120]$", "U100a200": "$U[100,200]$", "U1000a1100": "$U[1000,1100]$"}
    ORDER = ["U1a100", "U10a100", "U100a120", "U100a200", "U1000a1100", "JobsCorre", "MaqCorre"]

    def f2(v):
        s = f"{v:.2f}" if abs(v) >= 0.005 else "0.00"
        return s.replace("-", "$-$")

    def beyond(ty, sp, k):
        t = TF.loc[f"A-{ty}-{sp}-{k}"]
        return bool(t.confirmada) and not bool(t["equivalente_0.05"])

    L = ["% Auto-generated by analysis/make_table_journal.py", "\\begin{table}[t]",
         "\\caption{Standard benchmark of Fanjul-Peyro and Ruiz: gain over random choice (points of makespan, positive = better; $100$ test instances per type and space, $T=1000$ iterations, three seeds) of the validated action (val), of Q-Learning (ql) and of the best of the seven learners in each cell (best; the learner is named), and the mean gap of the validated action to the best known solution (\\%). Bold: gain over random choice confirmed (Holm within learner, $21$ cells) and not equivalent to zero at the margin $\\pm0.05$. B5: five destruction sizes; B15: three strategies $\\times$ five sizes; B30: B15 without and with local search.}",
         "\\label{tab:fanjul}", "\\centering", "{\\scriptsize\\setlength{\\tabcolsep}{3pt}", "\\resizebox{\\textwidth}{!}{%", "\\begin{tabular}{@{}l" + "rrrlr" * 3 + "@{}}", "\\toprule",
         " & \\multicolumn{5}{c}{B5} & \\multicolumn{5}{c}{B15} & \\multicolumn{5}{c}{B30} \\\\", "\\cmidrule(lr){2-6}\\cmidrule(lr){7-11}\\cmidrule(lr){12-16}",
         "Type" + " & val & ql & best & & gap" * 3 + " \\\\", "\\midrule"]
    for ty in ORDER:
        cells = []
        for sp in ("B5", "B15", "B30"):
            r = F[(F.space == sp) & (F.type == ty)].iloc[0]
            kb = max(LRN, key=lambda k: r[f"g_{k}"])
            qs = f2(r.g_ql)
            if beyond(ty, sp, "ql") and r.g_ql > 0:
                qs = f"\\textbf{{{qs}}}"
            bs = f2(r[f"g_{kb}"])
            if beyond(ty, sp, kb) and r[f"g_{kb}"] > 0:
                bs = f"\\textbf{{{bs}}}"
            cells += [f2(r.g_val), qs, bs, kb, f"{r.gap_val:.1f}"]
        L.append(NAMES[ty] + " & " + " & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}}}", "\\end{table}"]
    write("tab_fanjul.tex", L)
    print("tab_fanjul.tex")

# ---------------------------------------------------------------- order sensitivity of the default Q-Learning (Entradas 258, 260, 261)
if (R / "mech2_B30_entrada258.csv").exists() and (R / "entrada260_qperm_cells_fanjul.csv").exists() and (R / "entrada261_qperm_pcmax_cells.csv").exists():
    import sys
