print("tab_sim.tex, tab_empirical.tex")

# ---------------------------------------------------------------- published R||Cmax families (Entradas 254 and 255)
c254 = pd.read_csv(R / "entrada254_ur_external_cells.csv")
c255 = pd.read_csv(R / "entrada255_ext_competitors_cells.csv")
t254 = pd.read_csv(R / "entrada254_ur_external_tests.csv").set_index("id")
t255 = pd.read_csv(R / "entrada255_ext_competitors_tests.csv").set_index("id")
C = c254.merge(c255[["fam", "space", "g_cfg", "g_q", "g_iq", "g_fr"]], on=["fam", "space"])
FAM = {"unc": "uncorrelated", "cj": "correlated jobs", "cm": "correlated machines"}
COLS = [("g_val", "val", None), ("g_cfg", "cfg", t255), ("g_ql", "ql", t254), ("g_q", "q", t255), ("g_ucb", "ucb", t254), ("g_pg", "pg", t254),
        ("g_alns", "alns", t254), ("g_qo", "qo", t254), ("g_iq", "iq", t255), ("g_fr", "fr", t255)]


def cell(r, col, key, tests):
    v = r[col]
    s = f"{v:.2f}" if abs(v) >= 0.005 else "0.00"
    s = s.replace("-", "$-$")
    if tests is not None:
        t = tests.loc[f"A-{r.fam}-{r.space}-{key}"]
        if bool(t.confirmada) and not bool(t["equivalente_0.05"]) and v > 0:
            s = f"\\textbf{{{s}}}"
    return s


L = ["% Auto-generated by analysis/make_table_journal.py", "\\begin{table}[t]",
     "\\caption{Gains over random choice (points of makespan, positive = better) on the three published families of $R||C_{\\max}$ (generated from the description of \\citet{AbladEtAl2021}; $500$ test instances per family and space, $T=1000$ iterations). $h_{\\mathrm{cf}}$: cross-fitted headroom; val: validated static action; cfg: irace-configured static action; ql, ucb, pg, alns, qo: Q-Learning, UCB1, policy gradient, ALNS roulette, optimistic Q-Learning; q: irace-tuned Q-Learning; iq, fr: the two published AOS designs. Bold: gain over random choice confirmed (Holm within method) and not equivalent to zero at the margin $\\pm0.05$. No column beats the validated one beyond the margin; irace's static action is at parity with it.}",
     "\\label{tab:families}", "\\centering", "{\\scriptsize\\setlength{\\tabcolsep}{3.5pt}", "\\resizebox{\\textwidth}{!}{%", "\\begin{tabular}{@{}llrrrrrrrrrrr@{}}", "\\toprule",
     "Family & Actions & $h_{\\mathrm{cf}}$ & val & cfg & ql & q & ucb & pg & alns & qo & iq & fr \\\\", "\\midrule"]
order = ["g_val", "g_cfg", "g_ql", "g_q", "g_ucb", "g_pg", "g_alns", "g_qo", "g_iq", "g_fr"]
keymap = {c: (k, t) for c, k, t in COLS}
for _, r in C.iterrows():
    cells = [f"{r.h_cf:.2f}"] + [cell(r, c, keymap[c][0], keymap[c][1]) for c in order]
    L.append(f"{FAM[r.fam]} & {5 if r.space == 'S5' else 15} & " + " & ".join(cells) + " \\\\")
L += ["\\bottomrule", "\\end{tabular}}}", "\\end{table}"]
write("tab_families.tex", L)
print("tab_families.tex")

# ---------------------------------------------------------------- wide tables of the CEC version, adapted to the single-column journal layout
for stem in ("tab_agents", "tab_hosts"):
    t = (ROOT / "cec" / f"{stem}.tex").read_text(encoding="utf-8")
    t = t.replace("\\begin{table*}", "\\begin{table}").replace("\\end{table*}", "\\end{table}")
    t = t.replace("\\begin{tabular}", "\\resizebox{\\textwidth}{!}{\\begin{tabular}", 1).replace("\\end{tabular}}", "\\end{tabular}}}", 1)
    write(f"{stem}_j.tex", [t.rstrip("\n")])
print("tab_agents_j.tex, tab_hosts_j.tex")

# ---------------------------------------------------------------- standard benchmark of Fanjul-Peyro and Ruiz (Entrada 256)
if (R / "entrada256_fanjul_cells.csv").exists():
    F = pd.read_csv(R / "entrada256_fanjul_cells.csv")
    TF = pd.read_csv(R / "entrada256_fanjul_tests.csv").set_index("id")
    LRN = ["ql", "ucb", "pg", "alns", "qo", "iq", "fr"]
    NAMES = {"JobsCorre": "correlated jobs", "MaqCorre": "correlated machines", "U1a100": "$U[1,100]$", "U10a100": "$U[10,100]$", "U100a120": "$U[100,120]$", "U100a200": "$U[100,200]$", "U1000a1100": "$U[1000,1100]$"}
    ORDER = ["U1a100", "U10a100", "U100a120", "U100a200", "U1000a1100", "JobsCorre", "MaqCorre"]

    def f2(v):
        s = f"{v:.2f}" if abs(v) >= 0.005 else "0.00"
        return s.replace("-", "$-$")

    def beyond(ty, sp, k):
        t = TF.loc[f"A-{ty}-{sp}-{k}"]
        return bool(t.confirmada) and not bool(t["equivalente_0.05"])

    L = ["% Auto-generated by analysis/make_table_journal.py", "\\begin{table}[t]",
         "\\caption{Standard benchmark of Fanjul-Peyro and Ruiz: gain over random choice (points of makespan, positive = better; $100$ test instances per type and space, $T=1000$ iterations, three seeds) of the validated action (val), of Q-Learning (ql) and of the best of the seven learners in each cell (best; the learner is named), and the mean gap of the validated action to the best known solution (\\%). Bold: gain over random choice confirmed (Holm within learner, $21$ cells) and not equivalent to zero at the margin $\\pm0.05$. B5: five destruction sizes; B15: three strategies $\\times$ five sizes; B30: B15 without and with local search.}",
         "\\label{tab:fanjul}", "\\centering", "{\\scriptsize\\setlength{\\tabcolsep}{3pt}", "\\resizebox{\\textwidth}{!}{%", "\\begin{tabular}{@{}l" + "rrrlr" * 3 + "@{}}", "\\toprule",
         " & \\multicolumn{5}{c}{B5} & \\multicolumn{5}{c}{B15} & \\multicolumn{5}{c}{B30} \\\\", "\\cmidrule(lr){2-6}\\cmidrule(lr){7-11}\\cmidrule(lr){12-16}",
         "Type" + " & val & ql & best & & gap" * 3 + " \\\\", "\\midrule"]
    for ty in ORDER:
        cells = []
        for sp in ("B5", "B15", "B30"):
            r = F[(F.space == sp) & (F.type == ty)].iloc[0]
            kb = max(LRN, key=lambda k: r[f"g_{k}"])
            qs = f2(r.g_ql)
            if beyond(ty, sp, "ql") and r.g_ql > 0:
                qs = f"\\textbf{{{qs}}}"
            bs = f2(r[f"g_{kb}"])
            if beyond(ty, sp, kb) and r[f"g_{kb}"] > 0:
                bs = f"\\textbf{{{bs}}}"
            cells += [f2(r.g_val), qs, bs, kb, f"{r.gap_val:.1f}"]
        L.append(NAMES[ty] + " & " + " & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}}}", "\\end{table}"]
    write("tab_fanjul.tex", L)
    print("tab_fanjul.tex")
