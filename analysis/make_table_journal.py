# ---------------------------------------------------------------- published R||Cmax families (Entradas 254 and 255)
c254 = pd.read_csv(R / "entrada254_ur_external_cells.csv")
c255 = pd.read_csv(R / "entrada255_ext_competitors_cells.csv")
t254 = pd.read_csv(R / "entrada254_ur_external_tests.csv").set_index("id")
t255 = pd.read_csv(R / "entrada255_ext_competitors_tests.csv").set_index("id")
C = c254.merge(c255[["fam", "space", "g_cfg", "g_q", "g_iq", "g_fr"]], on=["fam", "space"])
FAM = {"unc": "uncorrelated", "cj": "correlated jobs", "cm": "correlated machines"}
COLS = [("g_val", "val", None), ("g_cfg", "cfg", t255), ("g_ql", "ql", t254), ("g_q", "q", t255), ("g_ucb", "ucb", t254), ("g_pg", "pg", t254),
        ("g_alns", "alns", t254), ("g_qo", "qo", t254), ("g_iq", "iq", t255), ("g_fr", "fr", t255)]


def cell(r, col, key, tests):
    v = r[col]
    s = f"{v:.2f}" if abs(v) >= 0.005 else "0.00"
    s = s.replace("-", "$-$")
    if tests is not None:
        t = tests.loc[f"A-{r.fam}-{r.space}-{key}"]
        if bool(t.confirmada) and not bool(t["equivalente_0.05"]) and v > 0:
            s = f"\\textbf{{{s}}}"
    return s


L = ["% Auto-generated by analysis/make_table_journal.py", "\\begin{table}[t]",
     "\\caption{Gains over random choice (points of makespan, positive = better) on the three published families of $R||C_{\\max}$ (generated from the description of \\citet{AbladEtAl2021}; $500$ test instances per family and space, $T=1000$ iterations). $h_{\\mathrm{cf}}$: cross-fitted headroom; val: validated static action; cfg: irace-configured static action; ql, ucb, pg, alns, qo: Q-Learning, UCB1, policy gradient, ALNS roulette, optimistic Q-Learning; q: irace-tuned Q-Learning; iq, fr: the two published AOS designs. Bold: gain over random choice confirmed (Holm within method) and not equivalent to zero at the margin $\\pm0.05$. No column beats the validated one beyond the margin; irace's static action is at parity with it.}",
     "\\label{tab:families}", "\\centering", "{\\scriptsize\\setlength{\\tabcolsep}{3.5pt}", "\\resizebox{\\textwidth}{!}{%", "\\begin{tabular}{@{}llrrrrrrrrrrr@{}}", "\\toprule",
     "Family & Actions & $h_{\\mathrm{cf}}$ & val & cfg & ql & q & ucb & pg & alns & qo & iq & fr \\\\", "\\midrule"]
