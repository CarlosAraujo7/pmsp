"""Gera as tabelas da versao de periodico que nao existem na versao do CEC (journal/tab_*.tex), a partir dos arquivos de resultados:
  tab_sim.tex        simulacao do estimador de folga (Entrada 257)
  tab_empirical.tex  decaimento do oraculo de uma semente nos dados reais (Entrada 257)
  tab_families.tex   as familias publicadas de R||Cmax (Entradas 254 e 255)         [quando os arquivos existirem]
  tab_fanjul.tex     o benchmark padrao de Fanjul-Peyro e Ruiz (Entrada 256)        [quando os arquivos existirem]
Uso: python analysis/make_table_journal.py"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
J = ROOT / "journal"


def write(name, lines):
    (J / name).write_text("\n".join(lines) + "\n", encoding="utf-8")


# ---------------------------------------------------------------- simulation of the estimator
S = pd.read_csv(R / "entrada257_sim_crossfit.csv")
L = ["% Auto-generated by analysis/make_table_journal.py", "\\begin{table}[t]",
     "\\caption{Monte Carlo check of the headroom estimators ($20{,}000$ instances per row; action means $\\mu_a=\\tau z_a$, $z_a\\sim N(0,1)$; run-to-run noise $\\sigma$; the cross-fitted estimator chooses on two runs and evaluates on two others). $H$: true headroom; $\\hat H_1$: one-seed oracle; best of 4, same runs: the minimum over actions of the mean of four runs, chosen and evaluated on the same runs;$\\hat H_{\\mathrm{cf}}$: cross-fitted oracle; regret: expected loss of the selected action. With $\\tau=0$ there is nothing to gain.}",
     "\\label{tab:sim}", "\\centering", "{\\scriptsize\\setlength{\\tabcolsep}{4pt}", "\\begin{tabular}{@{}rrrrrrrr@{}}", "\\toprule",
     "$A$ & $\\tau$ & $\\sigma$ & $H$ & $\\hat H_1$ & best of 4, same runs & $\\hat H_{\\mathrm{cf}}$ & regret \\\\", "\\midrule"]
for _, r in S.iterrows():
    L.append(f"{int(r.A)} & {r.tau:.2f} & {r.sigma:.1f} & {r.H_true:.3f} & {r.H_um:.3f} & {r.H_mesmas_k:.3f} & {r.H_cv:.3f} & {r.regret_cv:.3f} \\\\")
L += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
write("tab_sim.tex", L)

E = pd.read_csv(R / "entrada257_empirical_decay.csv")
L = ["% Auto-generated by analysis/make_table_journal.py", "\\begin{table}[t]",
     "\\caption{The one-seed oracle on real data (unrelated machines, $1{,}200$ instances, four runs per action and instance): gain over random choice, in points, of the best action per instance when it is chosen and evaluated on the same runs (one, two or four runs) and when it is chosen on two runs and evaluated on the other two (cross-fitted).}",
     "\\label{tab:empirical}", "\\centering", "{\\scriptsize\\setlength{\\tabcolsep}{5pt}", "\\begin{tabular}{@{}lrrrr@{}}", "\\toprule",
     " & one run & best of two (same) & best of four (same) & cross-fitted (2+2) \\\\", "\\midrule"]
for _, r in E.iterrows():
    L.append(f"{r.space} & {r.um_semente:.3f} & {r.melhor_de_2_mesmas:.3f} & {r.melhor_de_4_mesmas:.3f} & {r.cv_2mais2:.3f} \\\\")
