# ---------------------------------------------------------------- long horizon T = 10,000 on the standard benchmark (Entrada 258, long-horizon part)
TYPE_NAMES = {"JobsCorre": "correlated jobs", "MaqCorre": "correlated machines", "U1a100": "$U[1,100]$", "U10a100": "$U[10,100]$", "U100a120": "$U[100,120]$",
              "U100a200": "$U[100,200]$", "U1000a1100": "$U[1000,1100]$"}
TYPE_ORDER = ["U1a100", "U10a100", "U100a120", "U100a200", "U1000a1100", "JobsCorre", "MaqCorre"]
LRN7 = ["ql", "ucb", "pg", "alns", "qo", "iq", "fr"]


def f2x(v):
    s = f"{v:.2f}" if abs(v) >= 0.005 else "0.00"
    return s.replace("-", "$-$")


if (R / "entrada258L_longT_cells.csv").exists():
    CL = pd.read_csv(R / "entrada258L_longT_cells.csv")
    TL = pd.read_csv(R / "entrada258L_longT_tests.csv").set_index("id")

    def beyond_l(ty, k):
        t = TL.loc[f"A-{ty}-{k}"]
        return bool(t.confirmada) and not bool(t["equivalente_0.05"])

    LL = ["% Auto-generated by analysis/make_table_journal.py", "\\begin{table}[t]",
          "\\caption{Standard benchmark, B30, longer horizon: gain over random choice (points of makespan, positive = better; $100$ test instances per type, three seeds) of the validated action at $T=1000$ and at $T=10{,}000$ (re-chosen at the long horizon), of the standard Q-Learning (ql), the ALNS roulette (alns) and of the best of the seven learners at $T=10{,}000$ (best; the learner is named), and the gap of the validated action to the best known solution (\\%). Bold: gain over random choice confirmed (Holm within learner, seven types) and not equivalent to zero at the margin $\\pm0.05$.}",
          "\\label{tab:long}", "\\centering", "{\\scriptsize\\setlength{\\tabcolsep}{4pt}", "\\resizebox{\\textwidth}{!}{%", "\\begin{tabular}{@{}lrrrrrlrr@{}}", "\\toprule",
          " & \\multicolumn{2}{c}{validated gain} & \\multicolumn{4}{c}{learners at $T=10{,}000$} & \\multicolumn{2}{c}{validated gap (\\%)} \\\\",
          "\\cmidrule(lr){2-3}\\cmidrule(lr){4-7}\\cmidrule(lr){8-9}",
          "Type & $T=10^3$ & $T=10^4$ & ql & alns & \\multicolumn{2}{c}{best} & $T=10^3$ & $T=10^4$ \\\\", "\\midrule"]
    for ty in TYPE_ORDER:
        r = CL[CL.type == ty].iloc[0]
        kb = max(LRN7, key=lambda k: r[f"g_{k}"])

        def bold_l(k):
            s = f2x(r[f"g_{k}"])
            return f"\\textbf{{{s}}}" if (beyond_l(ty, k) and r[f"g_{k}"] > 0) else s
        LL.append(f"{TYPE_NAMES[ty]} & {f2x(r.g_val_T1000)} & {f2x(r.g_val_T10000)} & {bold_l('ql')} & {bold_l('alns')} & {bold_l(kb)} & {kb} & {r.gap_val_T1000:.1f} & {r.gap_val_T10000:.1f} \\\\")
    LL.append("\\midrule")
    LL.append(f"mean & {CL.g_val_T1000.mean():.2f} & {CL.g_val_T10000.mean():.2f} & {f2x(CL.g_ql.mean())} & {f2x(CL.g_alns.mean())} & {f2x(CL.best.mean())} & & {CL.gap_val_T1000.mean():.1f} & {CL.gap_val_T10000.mean():.1f} \\\\")
    LL += ["\\bottomrule", "\\end{tabular}}}", "\\end{table}"]
