"""Tabela de classes sinteticas do artigo do CEC (cec/tab_classes.tex), gerada de results/entrada283_classtable.csv (Entrada 283): n x m, n/m, otimo provado, lacuna do aleatorio ao limite inferior, ganho da validada em pontos e em unidades de makespan, folga cruzada (espaco de 5 acoes).
Uso: python -m analysis.make_table_cec_classes"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
T = pd.read_csv(ROOT / "results" / "entrada283_classtable.csv")
T = T[T.espaco == "S5"].sort_values(["n_sobre_m", "n"]).reset_index(drop=True)
BS = chr(92)


def row(label, vals, fmt):
    return label + " & " + " & ".join(fmt(v) for v in vals) + " " + BS + BS


lines = [
    "% Auto-generated by analysis/make_table_cec_classes.py (results/entrada283_classtable.csv)",
    BS + "begin{table*}[t]",
    BS + "caption{The twelve synthetic classes of P$||" + BS + "Cmax$ (five-action space; $100$ test instances each). Random choice is close to the bound: it is at the bound in $7$--$96\\%$ of the runs and, on average, $0.04$--$1.24$ makespan units above it. "
    "The validated action gains $0.01$--$0.62$ units over random choice; the cross-fitted headroom is a lower bound of what a selector choosing one action per instance could gain. Proven optimal: the certified bound equals the best makespan found.}",
    BS + "label{tab:classes}",
    BS + "centering",
    "{" + BS + "scriptsize" + BS + "setlength{" + BS + "tabcolsep}{3.2pt}",
    BS + "begin{tabular}{@{}l" + "r" * len(T) + "@{}}",
    BS + "toprule",
    "Class $n" + BS + "times m$ & " + " & ".join(f"${int(r.n)}" + BS + f"times{int(r.m)}$" for r in T.itertuples()) + " " + BS + BS,
    BS + "midrule",
    row("$n/m$", T.n_sobre_m, lambda v: f"{v:.1f}".rstrip("0").rstrip(".") if v != int(v) else f"{int(v)}"),
    row("Proven optimal (\\%)", 100 * T.proven, lambda v: f"{v:.0f}"),
    row("Random at the bound (\\%)", 100 * T.no_limite, lambda v: f"{v:.0f}"),
    row("Random above the bound (units)", T.lacuna_unidades, lambda v: f"{v:.2f}"),
    row("Validated gain (pp)", T.g_val, lambda v: f"{v:.3f}"),
    row("Validated gain (units)", T.g_val_unidades, lambda v: f"{v:.2f}"),
    row("Cross-fitted headroom (pp)", T.h_cf, lambda v: f"{v:.3f}"),
    BS + "bottomrule",
    BS + "end{tabular}}",
    BS + "end{table*}",
]
(ROOT / "cec" / "tab_classes.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("ok -> cec/tab_classes.tex", len(T), "classes;", f"at-bound {100 * T.no_limite.min():.0f}-{100 * T.no_limite.max():.0f}%; gap units {T.lacuna_unidades.min():.2f}-{T.lacuna_unidades.max():.2f}; validated units {T.g_val_unidades.min():.2f}-{T.g_val_unidades.max():.2f}")
