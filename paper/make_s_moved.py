"""Generate paper/s_moved.tex (material moved from the 46-page version to the supplement)
and paper/short/backmatter.tex from paper/learnheuristic_pmsp_long.tex.

Run from anywhere:  python paper/make_s_moved.py
The long file is the single source for the moved text; this script only selects line
ranges (1-indexed, inclusive) and fixes cross-references (S- prefixes, which only make
sense from the main document).
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
LONG = (HERE / "learnheuristic_pmsp_long.tex").read_text(encoding="utf-8").split("\n")


def rng(a, b):
    return LONG[a - 1:b]


# tables that now live in the main text (their \input lines are dropped here)
DROP_INPUTS = ("f25_igls_p.tex", "f26_igcvls.tex", "f12_stronger_baselines.tex")


def clean(lines):
    out = []
    for ln in lines:
        if ln.lstrip().startswith("%%"):
            continue
        if any(("\\input{%s}" % name) in ln for name in DROP_INPUTS):
            continue
        out.append(ln)
    text = "\n".join(out)
    text = re.sub(r"Supplementary Section~\\ref\{S-", r"Section~\\ref{", text)
    text = re.sub(r"Supplementary Table~\\ref\{S-", r"Table~\\ref{", text)
    text = re.sub(r"Supplementary\s+Section~\\ref\{S-", r"Section~\\ref{", text)
    text = re.sub(r"\\ref\{S-", r"\\ref{", text)
    text = re.sub(r"Section\s*\\ref\{S-", r"Section~\\ref{", text)
    return text


parts = []


def add(title, label, chunks, level="section", note=None):
    parts.append("\\%s{%s}\n\\label{%s}\n" % (level, title, label))
    if note:
        parts.append(note + "\n")
    for chunk in chunks:
        if isinstance(chunk, str):
            parts.append(chunk + "\n")
        else:
            parts.append(clean(rng(*chunk)) + "\n")


parts.append("%% Auto-generated by paper/make_s_moved.py from learnheuristic_pmsp_long.tex. Do not edit by hand.\n")

# ---------------------------------------------------------------- design details
add("Experimental design details", "sec:m-design", [
    "\\subsection{State representation}",
    (541, 574),
    "\\subsection{Iterated Greedy: strategies, reconstruction, acceptance and ablation ladder}",
    (621, 634),
    (659, 703),
    (712, 770),
    "\\subsection{Instances, methods and replications of the identical-machine study}",
    (834, 926),
], note="This section holds the details of the design that the main text only summarises.")

# ---------------------------------------------------------------- baselines
add("Identical machines: the ILS family and published baselines", "sec:m-baselines", [
    (928, 1065),
    (1067, 1159),  # the quality--time figure (1160--1170) now lives in the main text
], note="The comparisons that a typical study would report as the success of the learned policy; the main text (Section~\\ref{sec:f3f4-ablation}) summarises them.")

# ---------------------------------------------------------------- robustness of the null
add("Identical machines: robustness of the policy effect", "sec:m-robust", [
    (1179, 1212),
    (1214, 1247),
    (1249, 1271),
    (1273, 1286),
    (1304, 1352),
    (1369, 1396),
], note="Details of the analyses summarised in Section~\\ref{sec:f3f4-ablation}.")

# ---------------------------------------------------------------- recipe + LS
add("The recipe with a local search, at equal iterations and at equal CPU time", "sec:m-recipe", [
    (1427, 1450),
])

# ---------------------------------------------------------------- external
add("External validation on published identical-machine instances: full text", "sec:m-external", [
    (1455, 1520),
    (1539, 1559),
], note="Section~\\ref{sec:external} gives the condensed version.")

# ---------------------------------------------------------------- granularity / dispatch
add("Structural limits, granularity and the choice of mechanism per instance", "sec:m-granularity", [
    (1561, 1687),
], note="Material on the granularity of the processing times, which decides the direction between IG and ILS, and on a one-feature dispatch rule.")

# ---------------------------------------------------------------- unrelated
add("Unrelated machines: synthetic experiments and the headroom law in detail", "sec:m-unrelated", [
    (1701, 1719),
    (1721, 1818),
    (1844, 1847),
    (1859, 1861),
    (1863, 1884),
], note="Section~\\ref{sec:unrelated} gives the condensed version.")

(HERE / "s_moved.tex").write_text("\n".join(parts), encoding="utf-8")

# ---------------------------------------------------------------- back matter
back = clean(rng(2107, 2157))
back = back.replace("[Insert Repository\nLink/DOI, e.g., GitHub, Zenodo]",
                    "\\url{https://github.com/CarlosAraujo7/pmsp} (a DOI will be added on deposit)")
assert "Insert Repository" not in back
(HERE / "short").mkdir(exist_ok=True)
(HERE / "short" / "backmatter.tex").write_text(back + "\n", encoding="utf-8")
print("ok", sum(len(p) for p in parts), "chars in s_moved.tex;", len(back), "chars in backmatter.tex")
