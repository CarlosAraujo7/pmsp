"""Generate paper/s_moved.tex (material moved from the 46-page version to the supplement)
and paper/short/backmatter.tex from paper/learnheuristic_pmsp_long.tex.

Run from anywhere:  python paper/make_s_moved.py
The long file is the single source for the moved text; this script only selects line
ranges (1-indexed, inclusive) and fixes cross-references (S- prefixes, which only make
sense from the main document).
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
LONG = (HERE / "learnheuristic_pmsp_long.tex").read_text(encoding="utf-8").split("\n")


def rng(a, b):
    return LONG[a - 1:b]


# tables that now live in the main text (their \input lines are dropped here)
DROP_INPUTS = ("f25_igls_p.tex", "f12_stronger_baselines.tex")


def clean(lines):
    out = []
    for ln in lines:
        if ln.lstrip().startswith("%%"):
            continue
        if any(("\\input{%s}" % name) in ln for name in DROP_INPUTS):
            continue
        out.append(ln)
    text = "\n".join(out)
    text = re.sub(r"Supplementary Section~\\ref\{S-", r"Section~\\ref{", text)
    text = re.sub(r"Supplementary Table~\\ref\{S-", r"Table~\\ref{", text)
    text = re.sub(r"Supplementary\s+Section~\\ref\{S-", r"Section~\\ref{", text)
    text = re.sub(r"\\ref\{S-", r"\\ref{", text)
    text = re.sub(r"Section\s*\\ref\{S-", r"Section~\\ref{", text)
    return text


parts = []


def add(title, label, chunks, level="section", note=None):
    parts.append("\\%s{%s}\n\\label{%s}\n" % (level, title, label))
    if note:
        parts.append(note + "\n")
    for chunk in chunks:
        if isinstance(chunk, str):
            parts.append(chunk + "\n")
        else:
            parts.append(clean(rng(*chunk)) + "\n")


parts.append("%% Auto-generated by paper/make_s_moved.py from learnheuristic_pmsp_long.tex. Do not edit by hand.\n")

